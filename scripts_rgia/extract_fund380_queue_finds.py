"""Остаток очереди ф. 380 (описи 38–41): выбрать то немногое, что опознаётся по топониму.

Итог разбора 09.10.2026 — предел источника установлен окончательно:

* территории в электронном описании РГИА для этих дел НЕТ. Карточка дела содержит ровно
  пять полей (шифр, название фонда, опись, заголовок, крайние даты, число листов);
* описи 38–41 НЕ сгруппированы по губерниям. Аннотация описи 39 прямо говорит:
  «Карты и планы казенных и частных земель и лесов по всем губерниям и областям России».
  Проверено по номерам дел: соседние дела относятся к разным губерниям (Д. 1 Пермская,
  Д. 20 Келецкая, Д. 55 Лифляндская, Д. 86 Пермская) — восстановить разделы по соседству
  нельзя, таких разделов там просто нет;
* скана описи на портале нет, распознавать нечего — Vision тут неприменим;
* 146 записей вида «Карта губернии, с обозначением …» навсегда остаются без губернии:
  узнать её можно только по самому листу в читальном зале.

Поэтому единственное, что извлекается, — записи с узнаваемым топонимом наших губерний
в заголовке. Поиск подстрокой даёт много ложных: «Бельской и Беловодской» (конзаводы юга),
«Абельской волости» (Ковенская губ.), «Томско-Бельского» (Сибирь), «Зоборовской»,
«Мологинской». Поэтому список вердиктов задан поимённо, вручную, и это честнее регулярки.

Запуск:
    python -B scripts_rgia/extract_fund380_queue_finds.py
"""
from __future__ import annotations

import csv
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "output" / "rgia_fund380_handoff_package_20261008" / "review_queue.csv"
OUT = ROOT / "output" / f"rgia_f380_queue_finds_{time.strftime('%Y%m%d')}"

# Разбор вручную 09.10.2026 по заголовкам: шифр → (территория, статус, обоснование)
VERDICTS: dict[str, tuple[str, str, str]] = {
    "Ф. 380 Оп. 39 Д. 1586": (
        "Смоленская губерния", "keep",
        "все три названных уезда — Дорогобужский, Духовщинский, Поречский — Смоленской губернии"),
    "Ф. 380 Оп. 39 Д. 1816": (
        "Пермская губерния", "keep",
        "Верхотурский переселенческий район — Верхотурский уезд Пермской губернии; "
        "значит «карта губернии» здесь — карта Пермской"),
    "Ф. 380 Оп. 39 Д. 2058": (
        "Ярославская губерния", "keep",
        "Пошехонское городское общество — Пошехонский уезд Ярославской губернии"),
    "Ф. 380 Оп. 39 Д. 454": (
        "Ярославская губерния", "needs_human",
        "«Ростовское лесничество» — Ростовский уезд Ярославской губернии либо Ростов-на-Дону; "
        "по заголовку не различить"),
    "Ф. 380 Оп. 39 Д. 1288": (
        "Пермская губерния", "needs_human",
        "«Осинское имение» — Осинский уезд Пермской губернии либо созвучный топоним; "
        "владелец (купец Жирнов) по заголовку не локализуется"),
}
# Отвергнуто вручную — записано, чтобы при следующем проходе не разбирать заново
REJECTED = {
    "Ф. 380 Оп. 39 Д. 403": "«Бельской и Беловодской волостей» — военно-конские заводы юга "
                            "(Беловодск), не Бельский уезд Смоленской",
    "Ф. 380 Оп. 39 Д. 709": "«Абельской волости» — Ковенская губерния; подстрока «бельск» "
                            "попала внутрь слова",
    "Ф. 380 Оп. 39 Д. 1561": "Кухтеринский, Томско-Бельский, Суражевский подрайоны — Сибирь",
    "Ф. 380 Оп. 39 Д. 1707": "«Зоборовской лесной дачи» — подстрока «боровск» внутри слова",
    "Ф. 380 Оп. 39 Д. 1708": "«Северо-Мологинской» — подстрока «молог» внутри слова, "
                             "не Мологский уезд",
    "Ф. 380 Оп. 41 Д. 85": "планы ЗДАНИЙ лесных школ по всей империи (§1.2 сооружение, "
                           "не территория); Лихвинское лесничество — одно из десяти в списке",
}
COLS = ["fund_code", "territory", "status", "reason", "title", "date_raw",
        "year_from", "year_to", "sheets", "url"]


def main() -> int:
    rows = list(csv.DictReader(SRC.open(encoding="utf-8-sig")))
    by_code = {r.get("fund_code", ""): r for r in rows}
    out_rows, missing = [], []
    for code, (terr, status, reason) in VERDICTS.items():
        r = by_code.get(code)
        if r is None:
            missing.append(code)
            continue
        out_rows.append({"fund_code": code, "territory": terr, "status": status,
                         "reason": reason, "title": r.get("title", ""),
                         "date_raw": r.get("date_raw", ""),
                         "year_from": r.get("year_from", ""), "year_to": r.get("year_to", ""),
                         "sheets": r.get("sheets", ""), "url": r.get("url", "")})
    if missing:
        print(f"⚠️ не найдены в очереди: {missing}")
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "queue_finds.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS, extrasaction="ignore")
        w.writeheader()
        w.writerows(sorted(out_rows, key=lambda r: (r["status"], r["fund_code"])))

    keep = [r for r in out_rows if r["status"] == "keep"]
    (OUT / "QUEUE_FINDS_REPORT.json").write_text(json.dumps({
        "generated": time.strftime("%Y-%m-%d %H:%M"),
        "source": str(SRC),
        "queue_size": len(rows),
        "keep": len(keep),
        "needs_human": len(out_rows) - len(keep),
        "rejected_manually": len(REJECTED),
        "rejected": REJECTED,
        "limit_of_source": (
            "Территория для остальных записей описей 38-41 онлайн недоступна: карточка дела "
            "содержит пять полей без территории, описи не сгруппированы по губерниям "
            "(аннотация описи 39: «по всем губерниям и областям России»), скана описи на "
            "портале нет. 146 записей «Карта губернии, с обозначением …» определимы только "
            "по самому листу в читальном зале."),
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"очередь: {len(rows)} записей")
    print(f"опознано по топониму: {len(out_rows)} (в каталог {len(keep)}, "
          f"на решение {len(out_rows) - len(keep)})")
    print(f"отвергнуто вручную как ложные совпадения: {len(REJECTED)}")
    for r in sorted(out_rows, key=lambda r: r["status"]):
        print(f"  [{r['status']:<11}] {r['fund_code']:<22} {r['territory']:<20} "
              f"{r['title'][:60]}")
    print(f"\nвыход: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
