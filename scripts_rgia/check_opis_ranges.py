"""Проверка описей-диапазонов ф. 380: не потеряна ли наша губерния внутри диапазона.

Повод (09.10.2026): аннотация описи вида «…по губерниям и областям России: Пермская»
использовалась гейтом как ярлык ОДНОЙ губернии. На диапазонах («Черниговская-Ярославская»)
сравнение строкой не находило совпадения с нашими четырьмя губерниями, и опись отсеивалась
целиком. Так была потеряна опись 37 — 1 129 дел, внутри которых Ярославская губерния.

Здесь диапазон разворачивается по алфавиту: берём список губерний Российской империи,
находим границы диапазона и проверяем, попадает ли внутрь любая из наших четырёх.
Сеть не используется — читаются сохранённые состояния описей прогона.

Запуск:
    python -B scripts_rgia/check_opis_ranges.py
"""
from __future__ import annotations

import glob
import json
import re
import sys
from pathlib import Path

STATE_DIRS = [
    Path(r"C:\arch\output\rgia_fund380_20261003_v3_1\fund380_opis_state"),
    Path(__file__).resolve().parents[1] / "output" / "rgia_fund380_20261003_v3_1"
    / "fund380_opis_state",
]
OURS = ["Калужская", "Пермская", "Смоленская", "Ярославская"]

# Губернии и области Российской империи в алфавитном порядке — по нему строился фонд.
# Список нужен только для разворачивания диапазонов, поэтому включает и области.
GUBERNII = [
    "Акмолинская", "Амурская", "Архангельская", "Астраханская", "Бакинская", "Батумская",
    "Бессарабская", "Виленская", "Витебская", "Владимирская", "Вологодская", "Волынская",
    "Воронежская", "Вятская", "Гродненская", "Дагестанская", "Донская",
    "Екатеринославская", "Елисаветпольская",
    "Енисейская", "Забайкальская", "Закаспийская", "Иркутская", "Казанская", "Калужская",
    "Камчатская", "Карсская", "Киевская", "Ковенская", "Костромская", "Курляндская",
    "Курская", "Кутаисская", "Лифляндская", "Минская", "Могилевская", "Московская",
    "Нижегородская", "Новгородская", "Олонецкая", "Оренбургская", "Орловская", "Пензенская",
    "Пермская", "Подольская", "Полтавская", "Приморская", "Псковская", "Рязанская",
    "Самарская", "Самаркандская", "С.-Петербургская", "Санкт-Петербургская", "Саратовская",
    "Сахалинская", "Семипалатинская", "Семиреченская", "Симбирская", "Смоленская",
    "Ставропольская", "Сыр-Дарьинская", "Таврическая", "Тамбовская", "Ташкентская",
    "Тверская", "Терская", "Тифлисская", "Тобольская", "Томская", "Тульская", "Тургайская",
    "Уральская", "Уфимская", "Ферганская", "Финляндская", "Харьковская", "Херсонская",
    "Холмская", "Черниговская", "Черноморская", "Эриванская", "Эстляндская", "Якутская",
    "Ярославская",
]
IDX = {g.lower(): i for i, g in enumerate(GUBERNII)}
# В аннотациях ф. 380 латинская «K» подменяет кириллическую «К» — нормализуем
FIX = str.maketrans({"K": "К", "H": "Н", "C": "С", "P": "Р", "A": "А", "B": "В",
                     "E": "Е", "M": "М", "O": "О", "T": "Т", "X": "Х"})


def tail(annotation: str) -> str:
    """Хвост аннотации после двоеточия — там перечень губерний."""
    a = (annotation or "").translate(FIX).strip()
    return a.split(":")[-1].strip().rstrip(".").strip() if ":" in a else ""


def resolve(part: str) -> tuple[list[str], str]:
    """Вернуть губернии, покрытые куском аннотации, и как это определено."""
    part = part.strip()
    if not part:
        return [], "пусто"
    # хвост бывает с довеском: «Волынская - Гродненская. Указатель…» — режем по точке
    part = re.split(r"\.\s+[А-ЯЁA-Z]", part)[0].strip().rstrip(".")
    # сначала целиком: «С.-Петербургская» содержит дефис, но это одно название
    if part.lower() in IDX:
        return [part], "одна губерния"
    m = re.match(r"^(.+?)\s*[-–—]\s*(.+)$", part)
    if m:
        a, b = m.group(1).strip().lower(), m.group(2).strip().lower()
        ia, ib = IDX.get(a), IDX.get(b)
        if ia is not None and ib is not None:
            lo, hi = min(ia, ib), max(ia, ib)
            return GUBERNII[lo:hi + 1], f"диапазон {GUBERNII[lo]}…{GUBERNII[hi]}"
        return [], f"диапазон НЕ РАЗОБРАН ({part})"
    return [], f"не губерния ({part[:40]})"


def main() -> int:
    state_dir = next((d for d in STATE_DIRS if d.exists()), None)
    if state_dir is None:
        print("не найдена папка состояний описей")
        return 1

    rows = []
    for f in glob.glob(str(state_dir / "*.json")):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        rows.append((int(d.get("opis_number") or 0), d.get("opis_annotation") or ""))
    rows.sort()

    print(f"{'оп.':<5}{'аннотация (хвост)':<34}{'покрывает':<30}наши внутри")
    lost, ok_ours = [], []
    for num, ann in rows:
        t = tail(ann)
        covered, how = resolve(t)
        ours_in = [g for g in OURS if g in covered]
        flag = ""
        if ours_in:
            flag = "★ " + ", ".join(ours_in)
            (ok_ours if len(covered) == 1 else lost).append((num, t, ours_in))
        print(f"{num:<5}{t[:33]:<34}{how[:29]:<30}{flag}")

    print("\n— ОПИСИ-ДИАПАЗОНЫ, ВНУТРИ КОТОРЫХ ЕСТЬ НАША ГУБЕРНИЯ —")
    if not lost:
        print("  нет")
    for num, t, ours_in in lost:
        print(f"  оп. {num}: «{t}» → {', '.join(ours_in)}")
    print("\n— одиночные описи наших губерний (собраны штатно) —")
    for num, t, ours_in in ok_ours:
        print(f"  оп. {num}: {t}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
