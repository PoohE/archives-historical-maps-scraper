"""Независимая сверка: сколько дел распознано против числа ед. хр. по путеводителю архива.

Путеводитель — внешний источник, он не участвовал в распознавании, поэтому совпадение
числа дел подтверждает полноту прохода, а недобор прямо указывает, какую опись
перепроверять. Числа ед. хр. взяты из `output/gaso_putevoditel_20261008/MEZHEVANIE_FONDY.md`
с учётом исправленных номеров фондов (решение 13.10: ключ — Электронный каталог архива).

Запуск:
    python -B scripts_gaso/check_against_putevoditel.py C:\\arch\\output\\gaso_package_20261013
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

# фонд → (ед. хр. по путеводителю, название)
PUTEVODITEL = {
    # архив в предисловии к описи указывает 3079 дел за 1770–1916;
    # путеводитель даёт 3110 ед. хр. — берём число архива как более точное
    "814": (3079, "Смоленская межевая контора"),
    "428": (1333, "Ельнинская уездная землеустроительная"),
    "237": (1227, "Сычевская уездная землеустроительная"),
    "576": (651, "Смоленская губернская посредническая комиссия"),
    "334": (96, "Смоленская губернская землеустроительная"),
    "458": (61, "Рославльская уездная землеустроительная"),
    "88": (57, "Отряд по составлению владенных записей"),
    "1027": (54, "Велижская уездная землеустроительная"),
    "89": (50, "Краснинская уездная землеустроительная"),
    "998": (28, "Смоленское съёмочное отделение"),
    "87": (26, "Смоленская уездная землеустроительная"),
    "1063": (22, "Комиссия по оценке имуществ под железную дорогу"),
    "560": (16, "Гжатская уездная землеустроительная"),
    "666": (15, "Начальник городской съёмки"),
    "562": (12, "Духовщинская уездная землеустроительная"),
    "223": (8, "Смоленская уездная оценочная"),
    "523": (7, "Поречская уездная землеустроительная"),
    "495": (5, "Дорогобужская уездная землеустроительная"),
    "1073": (3, "Вяземская уездная землеустроительная"),
    "1191": (2, "Посредник по Рославльскому уезду"),
    "1071": (2, "Духовщинская уездная оценочная"),
    "1173": (1, "Посредник по Бельскому и Сычевскому уездам"),
    "1257": (1, "Посредник по Вяземскому, Гжатскому и Юхновскому"),
}


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    pkg = Path(sys.argv[1])
    rows = [json.loads(ln) for ln in (pkg / "gaso_all_records.jsonl").open(encoding="utf-8")]
    # ⚠️ Сверять надо ДЕЛА, а не строки: одна единица хранения нередко описана несколькими
    # строками описи (межевые книги сразу нескольких селений в одном деле). По ф. 814 это
    # 4719 строк против 3099 уникальных номеров при 3079 делах, заявленных архивом.
    by_fund: dict[str, set] = {}
    no_num = Counter()
    for r in rows:
        n = (r.get("n_delo") or "").strip()
        if n and n != "<нрзб>":
            by_fund.setdefault(r["fund"], set()).add(n)
        else:
            no_num[r["fund"]] += 1
    got = Counter({f: len(s) for f, s in by_fund.items()})

    # Описи устроены по-разному: у ф. 814 нумерация дел сквозная (ключ — уникальные номера),
    # а ф. 576 — журнал входящих, где номера дела нет вовсе (ключ — строки). Поэтому
    # считаем ОБА показателя и сигналим, только когда оба расходятся с заявленным.
    lines = Counter(r["fund"] for r in rows)

    print(f"{'фонд':<6} {'строк':>8} {'дел':>7} {'заявлено':>9} {'расхождение':>12}  фонд")
    total_best = total_decl = 0
    problems = []
    for fund, (decl, name) in sorted(PUTEVODITEL.items(), key=lambda kv: -kv[1][0]):
        n_uniq, n_lines = got.get(fund, 0), lines.get(fund, 0)
        best = min((abs(x - decl), x) for x in (n_uniq, n_lines))[1]
        total_best += best
        total_decl += decl
        diff = best - decl
        mark = "" if abs(diff) <= max(2, decl * 0.02) else "  ⚠"
        if mark:
            problems.append((fund, n_lines, n_uniq, decl, name))
        print(f"{fund:<6} {n_lines:>8} {n_uniq:>7} {decl:>9} {diff:>+12}{mark}  {name}")

    print(f"\nитого: по ближайшему счёту {total_best}, заявлено {total_decl}, "
          f"покрытие {total_best / total_decl * 100:.0f}%")
    if no_num:
        print("строк без номера дела: " + ", ".join(f"ф.{f} — {n}" for f, n in no_num.most_common(6)))
    if problems:
        print("\n⚠ требуют перепроверки:")
        for fund, n_lines, n_uniq, decl, name in problems:
            print(f"  ф. {fund}: строк {n_lines}, дел {n_uniq} против {decl} — {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
