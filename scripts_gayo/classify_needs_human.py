"""Разбор needs_human ГАЯО: территория задаётся ФОНДОМ, а не словами заголовка.

Гейт отложил 4537 записей по одной причине: картографический признак есть, а
территориального якоря в заголовке словарь не узнал («Выкопировка с плана отрубного
участка крестьянина Василия Оселкова»). Для общего гейта это правильно: он не знает,
откуда пришла запись.

Но у ГАЯО территория известна из фондовой принадлежности:
  ф. 455  Ярославский губернский межевой архив   — дела ярославские по определению
  ф. 82   Ярославская губернская чертежная       — то же
  ф. 80, 76, 452, 459, 462, 1441                  — губернские учреждения Ярославской губ.
  ф. 560  Коллекция картографических документов  — ОБЩЕРОССИЙСКАЯ (Киев, Амур, Туркестан),
                                                   территорию надо смотреть по заголовку

⚠️ Чего делать НЕЛЬЗЯ (проверено 18.10): выводить территорию из «словаря топонимов»,
собранного по принятым записям. В заголовках межевых книг больше всего слов с заглавной —
это имена владельцев, и словарь принимает «Андрея Прокофьевича Филисова» за топоним, а
«Межевую книгу участка Полевой владения Казанского» отправляет в Казань. Первый вариант
этого скрипта так и делал — результат был негодным.

Выход (в папку пакета):
    needs_human_resolved.csv — решение по каждой записи и его основание
    needs_human_review.csv   — то, что осталось человеку (ф. 560 без ясной территории)

Запуск:
    python -B scripts_gayo/classify_needs_human.py output/gayo_package_20261018
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

# Фонды ярославских учреждений: территория следует из фондовой принадлежности.
YAROSLAVL_FUNDS = {
    "455": "Ярославский губернский межевой архив",
    "82": "Ярославская губернская чертежная",
    "80": "Ярославское губернское правление",
    "76": "Ярославская губернская земская управа",
    "452": "губернское учреждение Ярославской губ.",
    "459": "губернское учреждение Ярославской губ.",
    "462": "губернское учреждение Ярославской губ.",
    "1441": "Угличское уездное лесничество",
}
# Коллекция ф. 560 собрана по всей империи — тут территорию читаем из заголовка.
COLLECTION = "560"

# Чужая география — только явные географические конструкции, НЕ отдельные корни:
# «Казанского» в фамилии владельца Казанью не делает (ловушка первого варианта).
ALIEN = re.compile(
    r"\bКиев\w*|\bМоскв\w*|\bС\.-?Петербург\w*|\bСанкт-Петербург\w*|\bПетроград\w*"
    r"|\bНахичеван\w*|\bАрхангельск(?:а|ого|ой|ом)\b|\bИркутск(?:а|ого|ой)\b"
    r"|\bТуркестан\w*|\bМаньчжури\w*|\bМонголи\w*|\bКита\w*|\bАмур\w*|\bСибир\w*"
    r"|\bКавказ\w*|\bКрым\w*|\bФинлянд\w*|\bВаршав\w*|\bРевел\w*|\bРиг[иа]\b"
    r"|\bОдесс\w*|\bАстрахан\w*|\bОренбург\w*|\bТифлис\w*|\bБаку\b|\bТашкент\w*"
    r"|\bХив[аы]\b|\bБухар\w*|\bКронштадт\w*|\bКамчатк\w*|\bСахалин\w*"
    r"|Европейск\w+ Росси\w*|Российск\w+ импери\w*|земного шара|полушари\w*"
    r"|\bЕвроп\w*\b|\bАзи[ияю]\b|\bАмерик\w*|\bмир[ао]в\w+ карт", re.I)
# Своя территория — губерния, уезды Ярославской губ. и соседние наши губернии проекта.
OURS = re.compile(
    r"Ярославл\w*|Ярославск\w*|Ростов\w*|Углич\w*|Углицк\w*|Мышкин\w*|Романов\w+-Борисоглеб"
    r"|Пошехон\w*|Любим\w*|Данилов\w*|Молог\w*|Рыбинск\w*|Калужск\w*|Смоленск\w*|Пермск\w*"
    r"|Волг[аи]\b|Шексн\w*|Которосл\w*|Сить\b", re.I)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("package")
    args = ap.parse_args()
    pkg = Path(args.package)

    rows = [json.loads(ln) for ln in (pkg / "gayo_needs_human.jsonl").open(encoding="utf-8")]
    verdict: Counter[str] = Counter()
    out = []
    for r in rows:
        fund = str(r.get("fund") or "")
        title = r.get("zagolovok", "")
        if fund in YAROSLAVL_FUNDS:
            v = "наша"
            why = f"фондовая принадлежность: ф.{fund} — {YAROSLAVL_FUNDS[fund]}"
        elif fund == COLLECTION:
            if OURS.search(title):
                v, why = "наша", "в заголовке названа территория проекта"
            elif ALIEN.search(title):
                v, why = "чужая", "в заголовке названа территория вне охвата проекта"
            else:
                v, why = "неясно", "коллекция ф.560, территория из заголовка не читается"
        else:
            v, why = "неясно", f"фонд {fund} не отнесён к ярославским — нужен просмотр"
        verdict[v] += 1
        out.append({**r, "verdict": v, "verdict_why": why})

    fields = list(out[0].keys()) if out else []

    def dump(name: str, data: list[dict]) -> None:
        with (pkg / f"{name}.csv").open("w", encoding="utf-8-sig", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
            w.writeheader()
            w.writerows(data)

    review = [r for r in out if r["verdict"] == "неясно"]
    dump("needs_human_resolved", out)
    dump("needs_human_review", review)

    print("решение по отложенным (основание — фонд, не слова заголовка):")
    for k, v in verdict.most_common():
        print(f"  {v:>5}  {k}")
    by_fund = Counter(f"ф.{r['fund']}" for r in review)
    if by_fund:
        print("на просмотр человеку:", dict(by_fund))
    print(f"\n→ {pkg / 'needs_human_resolved.csv'}")
    print(f"→ {pkg / 'needs_human_review.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
