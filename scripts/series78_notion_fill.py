def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    apply = ap.parse_args().apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))
    series = {title_of(p): p for p in query_all(client, SERIES_DS)}
    print(f"карточек серий: {len(series)}")

    # --- серия 7: создать, если нет
    s7 = series.get(S7_TITLE)
    if s7:
        upd = {k: {"rich_text": rt(v)} for k, v in S7_FIELDS.items() if is_empty(s7, k)}
        print(f"серия 7: карточка есть, пустых полей к заполнению {len(upd)}")
        if upd and apply:
            retry(lambda: client.pages.update(page_id=s7["id"], properties=upd))
            print("серия 7: обновлена")
    elif apply:
        props: dict = {"Название серии": {"title": [{"type": "text",
                                                     "text": {"content": S7_TITLE}}]}}
        props |= {k: {"number": v} for k, v in S7_NUMBERS.items()}
        props |= {k: {"rich_text": rt(v)} for k, v in S7_FIELDS.items()}
        props |= {k: {"select": {"name": v}} for k, v in S7_SELECTS.items()}
        page = retry(lambda: client.pages.create(
            parent={"database_id": SERIES_DB}, properties=props))
        print(f"серия 7: СОЗДАНА карточка {page['id']}, полей {len(props)}")
    else:
        print("серия 7: карточки НЕТ → будет создана, полей "
              f"{1 + len(S7_NUMBERS) + len(S7_FIELDS) + len(S7_SELECTS)}")

    # --- серия 8: только пустые поля
    s8 = series.get(S8_TITLE)
    if not s8:
        print(f"!! карточка «{S8_TITLE}» не найдена")
        return
    upd = {k: {"rich_text": rt(v)} for k, v in S8_FILL.items() if is_empty(s8, k)}
    skip = [k for k in S8_FILL if k not in upd]
    print(f"серия 8: заполнить пустых полей {len(upd)} ({', '.join(upd) or '—'}); "
          f"занятых не трогаем: {', '.join(skip) or '—'}")
    if upd and apply:
        retry(lambda: client.pages.update(page_id=s8["id"], properties=upd))
        print("серия 8: обновлена")


if __name__ == "__main__":
    main()
