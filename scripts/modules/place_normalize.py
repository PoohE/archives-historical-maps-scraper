"""
Нормализация поля «Место создания» (12) к внятному топониму (канон v1.6).

Правила:
- город в именительном падеже, современная орфография исторического названия
  («Санктпетербург»/«В Санктпетербурге»/«С.-Петербург» → «Санкт-Петербург»);
- историческое имя ЭПОХИ сохраняется («Свердловск» изд. 1928 не → «Екатеринбург»);
- снимаются квадратные скобки каталогизатора и ведущий предлог «в/во/въ»;
- не-топоним / обрезок парсинга / без цифр-мусор → пусто + причина (на проверку).

Дословная форма всегда остаётся в поле 21 «Описание» — здесь только чистое значение поля 12.

Публичная функция: normalize(raw) -> (value, reason)
  value  — канонический топоним или '' если распознать нельзя;
  reason — '' если ок, иначе код: 'place_unrecognized' / 'place_empty'.
"""
import re

# key (нижн. регистр, ё→е, только буквы) -> канонический топоним
ALIASES = {
    "санктпетербург": "Санкт-Петербург",
    "санктпетербурге": "Санкт-Петербург",
    "санктпетербургъ": "Санкт-Петербург",
    "спетербург": "Санкт-Петербург",     # С.-Петербург
    "спетербургъ": "Санкт-Петербург",
    "петербург": "Санкт-Петербург",
    "петербурге": "Санкт-Петербург",
    "спб": "Санкт-Петербург",
    "петроград": "Петроград",            # имя эпохи 1914–1924 — сохраняем
    "петрограде": "Петроград",
    "ленинград": "Ленинград",
    "ленинграде": "Ленинград",
    "москва": "Москва",
    "москве": "Москва",
    "мск": "Москва",
    "пермь": "Пермь",
    "перми": "Пермь",
    "свердловск": "Свердловск",
    "свердловске": "Свердловск",
    "ярославль": "Ярославль",
    "ярославле": "Ярославль",
    "усолье": "Усолье",
    "калуга": "Калуга",
    "калуге": "Калуга",
    "смоленск": "Смоленск",
    "смоленске": "Смоленск",
}

# признаки НЕ-топонима (мусор парсинга / служебное)
BLACKLIST_SUBSTR = ("заголовок", "загол.", "дела", "оригинал", "ориг.",
                    "без места", "б. м", "б.м", "s. l", "s.l", "not identified")
PREPOSITION_RE = re.compile(r"^(?:въ|во|в)\s+", re.I)


def _key(s: str) -> str:
    return re.sub(r"[^а-яё]", "", s.lower().replace("ё", "е"))


def normalize(raw):
    """Вернуть (канонический топоним, причина)."""
    if not raw or not raw.strip():
        return "", "place_empty"
    s = raw.strip().strip("[]").strip()          # снять скобки каталогизатора
    s = s.strip("[]().,;:—–- ").strip()
    s = PREPOSITION_RE.sub("", s).strip()        # снять ведущий предлог
    low = s.lower().replace("ё", "е")

    if re.search(r"\d", s):                        # цифры → обрезок («[1», «1863»)
        return "", "place_unrecognized"
    if any(b in low for b in BLACKLIST_SUBSTR):
        return "", "place_unrecognized"

    k = _key(s)
    if k in ALIASES:
        return ALIASES[k], ""
    # неизвестный, но правдоподобный топоним: кириллица, 1–3 слова, ≥3 букв
    words = s.split()
    if 1 <= len(words) <= 3 and len(k) >= 3 and re.fullmatch(r"[А-ЯЁа-яё\- ]+", s):
        # первое слово с заглавной, остальное как есть (Нижний Новгород)
        return s[0].upper() + s[1:], ""
    return "", "place_unrecognized"


# извлечение места издания из библиографической строки (поле 21 «Описание»)
# для восстановления, когда поле 12 = мусор. Имприт: «… — Место : издатель, год».
_IMPRINT_RE = re.compile(r"[.\]]?\s*[-–—]\s*([А-ЯЁ][^:\n]{1,45}?)\s*:")


def recover_from_description(desc):
    """Достать место издания из текста карточки → (топоним, причина) или ('', ...)."""
    if not desc:
        return "", "place_empty"
    m = _IMPRINT_RE.search(desc)
    if not m:
        return "", "place_unrecognized"
    return normalize(m[1])


if __name__ == "__main__":
    tests = ["Санктпетербург", "В Санктпетербурге", "[Санктпетербург", "С.-Петербург",
             "Санкт-Петербург", "[Ярославль", "[Усолье]", "Москва", "Свердловск",
             "Пермь", "[1", "Ориг. заголовок дела", "Нижний Новгород"]
    for t in tests:
        print(f"{t!r:32} -> {normalize(t)}")
