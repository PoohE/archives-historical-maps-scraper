def main() -> None:
    fix_stdout()
    OUT.mkdir(parents=True, exist_ok=True)
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    if not src.exists():
        sys.exit(f"нет выгрузки: {src}")

    pats = {k: re.compile(v, re.IGNORECASE) for k, v in SERIES.items()}
    total: Counter = Counter()
    ours: Counter = Counter()
    samples: dict[str, list[str]] = {k: [] for k in SERIES}
    n = 0
    for line in src.open(encoding="utf-8"):
        if not line.strip():
            continue
        n += 1
        f = (json.loads(line).get("fields") or {})
        blob = " ".join(
            str(f.get(k) or "") for k in ("Название источника", "Описание", "Серия")
        )
        if not blob.strip():
            continue
        g = None
        for lab, pat in pats.items():
            if not pat.search(blob):
                continue
            total[lab] += 1
            if g is None:
                g = our_gubernii(blob)
            if g:
                ours[lab] += 1
            if len(samples[lab]) < 3:
                samples[lab].append(
                    f"{f.get('Архив [авто]') or '?'}: "
                    f"{(f.get('Название источника') or '')[:110]}"
                )

    print(f"записей в выгрузке: {n}\n")
    print(f"{'серия':54s} {'всего':>6s} {'наши':>6s}")
    have, absent = [], []
    for lab in SERIES:
        c, o = total[lab], ours[lab]
        print(f"  {lab:52s} {c:6d} {o:6d}")
        (have if c else absent).append(lab)
    print(f"\nесть в каталоге хоть чем-то: {len(have)} из {len(SERIES)}")
    print(f"ОТСУТСТВУЮТ полностью: {len(absent)}")
    for lab in absent:
        print(f"    — {lab}")

    rep = {
        lab: {"всего": total[lab], "наши": ours[lab], "примеры": samples[lab]}
        for lab in SERIES
    }
    p = OUT / "catalog_check.json"
    p.write_text(json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n→ {p}")

    print("\nПРИМЕРЫ по найденным (до 2 на серию):")
    for lab in have:
        for s in samples[lab][:2]:
            print(f"  [{lab[:34]}] {s}")


if __name__ == "__main__":
    main()
