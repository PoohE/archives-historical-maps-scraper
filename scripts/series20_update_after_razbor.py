def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))
    card = next(x for x in query_all(c, SERIES_DS) if CARD in title_of(x))
    props = {k: {"rich_text": rt(v)} for k, v in F.items()}
    props["Хронология нижняя"] = {"number": 1859}
    props["Хронология верхняя"] = {"number": 1868}
    retry(lambda: c.pages.update(page_id=card["id"], properties=props))
    print(f"карточка обновлена: {title_of(card)}")


if __name__ == "__main__":
    main()
