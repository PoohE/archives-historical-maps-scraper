def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--card-only", action="store_true")
    args = ap.parse_args()

    if args.apply and LOCK.exists():
        sys.exit(f"уже идёт прогон (есть {LOCK.name}) — не запускаю второй")

    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    existing = [x for x in query_all(c, SERIES_DS) if "землеустроительных комисс" in title_of(x)]
    card = existing[0] if existing else None
    if card:
        print(f"карточка уже есть: {title_of(card)}")
    elif args.apply:
        card = retry(
            lambda: c.pages.create(
                parent={"database_id": SERIES_DB},
                properties={
                    k: ({"title": rt(v)} if k == "Название серии" else {"rich_text": rt(v)})
                    for k, v in FIELDS.items()
                },
            )
        )
        print(f"создана карточка: {NAME}")
    else:
        print(f"карточки нет — будет создана: {NAME}")

    if card and args.apply:
        props = {
            k: ({"title": rt(v)} if k == "Название серии" else {"rich_text": rt(v)})
            for k, v in FIELDS.items()
        }
        retry(lambda: c.pages.update(page_id=card["id"], properties=props))
        print("поля карточки записаны")

    rows = [json.loads(ln) for ln in LINKS.open(encoding="utf-8") if ln.strip()]
    pages = [r["page_id"] for r in rows if r["page_id"]]
    print(f"записей каталога под привязку: {len(pages)}")
    if not args.apply or args.card_only or card is None:
        for r in rows[:10]:
            print(f"   → [{r['basis']}] {r['arch']} ф.{r['fond']} {r['name'][:90]}")
        print("\nпривязка не выполнялась")
        return

    LOCK.write_text("series23", encoding="utf-8")
    try:
        n = skipped = 0
        for i, pid in enumerate(pages, 1):
            pg = retry(lambda pid=pid: c.pages.retrieve(page_id=pid))
            rel = (pg["properties"].get("Серия / массив") or {}).get("relation") or []
            if any(x["id"] == card["id"] for x in rel):
                skipped += 1
                continue
            retry(
                lambda pid=pid, rel=rel: c.pages.update(
                    page_id=pid,
                    properties={
                        "Серия / массив": {"relation": rel + [{"id": card["id"]}]}
                    },
                )
            )
            n += 1
            if i % 100 == 0:
                print(f"  {i}/{len(pages)}: связано {n}, уже были {skipped}", flush=True)
        print(f"ИТОГО связано: {n}; уже были связаны: {skipped}")
    finally:
        LOCK.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
