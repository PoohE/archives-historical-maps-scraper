def resolve_rgb(client: Client) -> str:
    """Найти id РГБ в справочнике «Архивы» по названию."""
    cursor = None
    while True:
        body: dict = {"page_size": 100}
        if cursor:
            body["start_cursor"] = cursor
        resp = retry(lambda body=body: client.data_sources.query(
            data_source_id="fedbea82-520d-4f03-b8bc-793a29a25e79", **body))
        for p in resp["results"]:
            name = next((("".join(x["plain_text"] for x in v["title"]))
                         for v in p["properties"].values() if v.get("type") == "title"), "")
            if "РГБ" in name or "государственная библиотека" in name.lower():
                return p["id"]
        if not resp.get("has_more"):
            raise SystemExit("РГБ не найдена в справочнике «Архивы»")
        cursor = resp["next_cursor"]


def props_for(rec: dict, rgb_id: str) -> dict:
    out: dict = {}
    for k, v in rec.items():
        if k.startswith("_") or v is None:
            continue
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            out[k] = {"number": v}
        elif k in SELECTS:
            out[k] = {"select": {"name": v}}
        elif k == "Название источника":
            out[k] = {"title": rt(v)}
        elif k == "Ссылка на онлайн-архив":
            out[k] = {"url": v}
        else:
            out[k] = {"rich_text": rt(v)}
    out["Архив хранения"] = {"relation": [{"id": rgb_id}]}
    out["Тип источника"] = {"relation": [{"id": B1}]}
    out["Охватываемая территория"] = {"relation": [{"id": EVR}]}
    if rec.get("_series"):
        out["Серия / массив"] = {"relation": [{"id": rec["_series"]}]}
    return out


def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", default="plan", choices=["plan", "apply", "verify"])
    args = ap.parse_args()

    outdir = Path(__file__).resolve().parents[1] / "output" / "znaki_records"
    outdir.mkdir(parents=True, exist_ok=True)
    done = outdir / "created.jsonl"

    if args.mode == "plan":
        for r in RECORDS:
            ser = "серия 3" if r["_series"] else "без серии"
            print(f"\n— {r['Название источника'][:95]}")
            print(f"   {r['Год источника']} | {r['Место создания']} | {r['Библиотечный шифр'][:60]}")
            print(f"   описание {len(r['Описание'])} зн. | {ser}")
        print(f"\nвсего к созданию: {len(RECORDS)}")
        return

    client = Client(auth=env("NOTION_TOKEN"))
    rgb_id = resolve_rgb(client)
    log(f"РГБ в справочнике: {rgb_id}")

    if args.mode == "apply":
        existing = set()
        if done.exists():
            existing = {json.loads(x)["title"]
                        for x in done.read_text(encoding="utf-8").splitlines() if x.strip()}
        with done.open("a", encoding="utf-8") as jl:
            for r in RECORDS:
                title = r["Название источника"]
                if title in existing:
                    log(f"пропуск (уже создано): {title[:60]}")
                    continue
                page = retry(lambda r=r: client.pages.create(
                    parent={"database_id": CATALOG}, properties=props_for(r, rgb_id)))
                jl.write(json.dumps({"title": title, "id": page["id"]}, ensure_ascii=False) + "\n")
                jl.flush()
                log(f"создано: {title[:70]}")
                time.sleep(SLEEP)
        return

    bad = 0
    for line in done.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        pid = rec["id"]
        props = retry(lambda pid=pid: client.pages.retrieve(pid))["properties"]
        shelf = "".join(x["plain_text"]
                        for x in props.get("Библиотечный шифр", {}).get("rich_text", []))
        ok = bool(shelf) and bool(props.get("Архив хранения", {}).get("relation"))
        bad += not ok
        print(("OK  " if ok else "НЕТ ") + rec["title"][:70] + f"  [{shelf[:40]}]")
        time.sleep(SLEEP)
    print(f"verify: расхождений {bad}")


if __name__ == "__main__":
    main()
