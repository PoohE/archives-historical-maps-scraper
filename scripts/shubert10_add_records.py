def props_for(rec: dict) -> dict:
    out: dict = {}
    for k, v in rec.items():
        if k.startswith("_"):
            continue
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            out[k] = {"number": v}
        elif k in SELECTS:
            out[k] = {"select": {"name": v}}
        elif k == "Название источника":
            out[k] = {"title": rt(v)}
        elif k == "Ссылка на онлайн-архив":
            out[k] = {"url": v}
        else:
            out[k] = {"rich_text": rt(v)}
    if rec["_arch"]:
        out["Архив хранения"] = {"relation": [{"id": i} for i in rec["_arch"]]}
    out["Тип источника"] = {"relation": [{"id": i} for i in rec["_type"]]}
    out["Охватываемая территория"] = {"relation": [{"id": i} for i in rec["_terr"]]}
    out["Серия / массив"] = {"relation": [{"id": SERIES}]}
    out["Типы отображаемых объектов"] = {"relation": [{"id": i} for i in rec["_obj"]]}
    return out


def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", default="plan", choices=["plan", "apply", "verify"])
    args = ap.parse_args()

    outdir = Path(__file__).resolve().parents[1] / "output" / "shubert10_records"
    outdir.mkdir(parents=True, exist_ok=True)
    done = outdir / "created.jsonl"

    if args.mode == "plan":
        for r in RECORDS:
            print(f"\n— {r['Название источника']}")
            print(f"   {r['Место хранения']} | {r.get('Библиотечный шифр', '—')} | "
                  f"{r['Год источника']} | 1:{r['Масштаб (знаменатель)']}")
            print(f"   описание: {len(r['Описание'])} зн.; территорий {len(r['_terr'])}, "
                  f"объектов {len(r['_obj'])}, архивов {len(r['_arch'])}")
        print(f"\nвсего к созданию: {len(RECORDS)}")
        return

    client = Client(auth=env("NOTION_TOKEN"))

    if args.mode == "apply":
        existing = set()
        if done.exists():
            existing = {json.loads(x)["title"]
                        for x in done.read_text(encoding="utf-8").splitlines() if x.strip()}
        with done.open("a", encoding="utf-8") as jl:
            for r in RECORDS:
                title = r["Название источника"]
                if title in existing:
                    log(f"пропуск (уже создано): {title[:70]}")
                    continue
                page = retry(lambda r=r: client.pages.create(
                    parent={"database_id": CATALOG}, properties=props_for(r)))
                jl.write(json.dumps({"title": title, "id": page["id"]},
                                    ensure_ascii=False) + "\n")
                jl.flush()
                log(f"создано: {title[:70]}")
                time.sleep(SLEEP)
        return

    bad = 0
    for line in done.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        pid = rec["id"]
        props = retry(lambda pid=pid: client.pages.retrieve(pid))["properties"]
        rel = [x["id"].replace("-", "") for x in props.get("Серия / массив", {}).get("relation", [])]
        ok = SERIES.replace("-", "") in rel
        bad += not ok
        print(("OK  " if ok else "НЕТ ") + rec["title"][:80])
        time.sleep(SLEEP)
    print(f"verify: расхождений {bad}")


if __name__ == "__main__":
    main()
