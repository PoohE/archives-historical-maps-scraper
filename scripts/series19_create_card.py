def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    existing = [x for x in query_all(c, SERIES_DS) if "есоустро" in title_of(x)]
    if existing:
        print(f"карточка уже есть: {title_of(existing[0])}")
    elif not args.apply:
        print(f"карточки нет — будет создана: «{NAME}»")
    else:
        props = {
            "Название серии": {"title": [{"text": {"content": NAME}}]},
            "Хронология нижняя": {"number": FIELDS["Хронология нижняя"]},
            "Хронология верхняя": {"number": FIELDS["Хронология верхняя"]},
        }
        for k, v in FIELDS.items():
            if isinstance(v, str) and k != "Название серии":
                props[k] = {"rich_text": rt(v)}
        retry(lambda: c.pages.create(parent={"database_id": SERIES_DB}, properties=props))
        print(f"карточка создана: {NAME}")

    if not BASELINE.exists():
        print(f"⚠️ выгрузки каталога нет, оценку кандидатов пропускаю: {BASELINE}")
        return
    n = 0
    for line in BASELINE.open(encoding="utf-8"):
        if not line.strip():
            continue
        f = (json.loads(line).get("fields") or {})
        if CAND.search(str(f.get("Название источника") or "")):
            n += 1
    print(f"записей каталога, похожих на лесоустроительные (офлайн, выгрузка 30.10): {n}")
    print("привязка НЕ выполняется: решение, что из них настоящий лесоустроительный "
          "комплект, — за приёмщиком")


if __name__ == "__main__":
    main()
