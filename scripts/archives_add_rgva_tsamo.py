def props_for(d: dict) -> dict:
    out: dict = {}
    for k, v in d.items():
        if k == "Название":
            out["Название"] = {"title": [{"text": {"content": v}}]}
        elif k == "Сайт":
            out["Сайт"] = {"url": v}
        elif k in ("Тип", "Приоритет", "Статус доступа", "Веб-поиск", "Метод поиска"):
            out[k] = {"select": {"name": v}}
        else:
            out[k] = {"rich_text": rt(v)}
    return out


def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    existing = {title_of(x): x["id"] for x in query_all(c, ARCHIVES_DS)}
    new_ids = []
    for d in CARDS:
        name = d["Название"]
        if name in existing:
            print("уже есть:", name)
            new_ids.append(existing[name])
            continue
        page = retry(
            lambda d=d: c.pages.create(
                parent={"database_id": ARCHIVES_DB}, properties=props_for(d)
            )
        )
        new_ids.append(page["id"])
        print("создана:", name)

    card = next(x for x in query_all(c, SERIES_DS) if "РККА" in title_of(x))
    have = [r["id"] for r in card["properties"]["Архивы"]["relation"]]
    merged = have + [i for i in new_ids if i not in have]
    retry(
        lambda: c.pages.update(
            page_id=card["id"],
            properties={"Архивы": {"relation": [{"id": i} for i in merged]}},
        )
    )
    print(f"серия 17: архивов в связи — {len(merged)}")


if __name__ == "__main__":
    main()
