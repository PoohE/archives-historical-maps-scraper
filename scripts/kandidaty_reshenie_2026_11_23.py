"""Решение по 23 064 записям «кандидат» по правилам владельца (23.11.2026). Только читает.

Решения владельца в этой сессии:
  1. Проверка выборкой по слоям: 60 записей ГАЯО ф. 455, по 30 на прочие слои; слой без
     брака (для источника — не более 1 ошибки) принимается целиком, с браком — сплошь.
     Итог выборки: проходят ГАЯО ф. 455, ГАСО-Урал, СОУНБ (Смоленск).
  2. Классы изданий: оставляем ВСЁ, что привязано к нашей территории (статистика, памятные
     книжки, списки населённых мест, метрические книги, ревизские сказки, сметы земств);
     отклоняем газеты («губернские/епархиальные ведомости» и пр.) и финансовые ведомости.
Действующие правила проекта: 1918+ — вне скоупа (список будущего); чужая губерния — отсев;
межгубернские и обзорные («Европейская Россия», империя) — наши; отсев с причиной, без
удаления.

Выход: output/kandidaty_proverka_2026-11-23/reshenie.csv (page_id, решение, причина) и сводка.
  python scripts/kandidaty_reshenie_2026_11_23.py output/notion_catalog_<метка>.csv
"""
import csv
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kandidaty_vyborka_2026_11_23 import OUR, OUT, stratum, year  # noqa: E402
from territory_gate import classify  # noqa: E402

PASSED = {"ГАЯО ф. 455", "ГАСО-Урал", "СОУНБ"}
# у этих держателей провенанс сам задаёт губернию (фонд или региональная библиотека)
REGIONAL = {"ГАЯО", "ГАСО-Урал", "ПГКБ", "СОУНБ", "СОУНБ (Свердловск)", "ГАСО", "ГАКО", "ГАПК"}
NEWSPAPER = re.compile(r"(губернск\w*|епархиальн\w*|областн\w*)\s+ведомост|народная свобода"
                       r"|\bгазет", re.I)
FINANCE = re.compile(r"ведомост\w*.{0,60}?(взнос|выкуп|погашен|рассрочк|рекрут|сличительн|"
                     r"капитальн\w* долг|материальн|зачетн|третн\w* и годов)", re.I)
SOVIET = re.compile(r"\bСССР\b|С\.С\.С\.Р|советск|Союза Советских|\bРСФСР\b|област\w* 19[2-9]\d", re.I)
# ⚠️ Только по описанию музейного предмета Госкаталога. Голое «Москв» ловило «пустошь
# Москвину» ярославских межевых книг и место издания «Москва» у книг о наших губерниях
# (45 ложных отсевов на первом прогоне 23.11) — та же ловушка подстроки, что у гейта.
MOSCOW = re.compile(r"команд\w* Москвы|за Земляным городом|в Белом городе|Китай-город", re.I)


CENSUS_VOL = re.compile(r"перепись населения Российской империи 1897 г\.{1,2}\s*(\d{1,2})\b", re.I)
CENSUS_OURS = {16: "Калужская", 31: "Пермская", 40: "Смоленская", 50: "Ярославская"}
FOREIGN_REGION = re.compile(
    r"Привислянск\w*|Полесск\w*|Северо-Западн\w*|Юго-Западн\w*|Прибалтийск\w*|Остзейск\w*|"
    r"Кавказ\w*|Закавказ\w*|Сибир\w*|Туркестан\w*|Степн\w* (?:генерал-губ|област)\w*|"
    r"Царств\w* Польск\w*|Финлянд\w*|Бессараб\w*|Малоросси\w*|Новоросси\w*|Войска Донского|"
    r"Уральск\w* област\w*|Сахалин\w*|Карсск\w*|Азиатск\w* Росси\w*(?!.*Европейск)", re.I)


OVERVIEW = re.compile(r"Европейск\w*|Российск\w* импери\w*|Всероссийск\w*|всей России", re.I)
VOLUME_OF = re.compile(r"(?:Вып\.|Выпуск|Ч\.|Т\.|Часть|Том)\s*\d+\s*[:.)]?\s*[^;/]{0,40}?"
                       + "(?:" + FOREIGN_REGION.pattern + ")", re.I)


def norm(t: str) -> str:
    return re.sub(r"\W+", " ", (t or "").lower()).strip()


def decide(r: dict) -> tuple[str, str]:
    title = r["Название источника"] or ""
    text = title + " " + (r["Описание"] or "")
    y = year(r)
    if y and y > 1917:
        data = [int(v) for v in re.findall(r"\b(1[6-9]\d\d)\b", title) if int(v) <= 1917]
        if data:
            return "владельцу", (f"издано в {y}, но данные за {min(data)}–{max(data)}: "
                                 "год печати ≠ год данных")
        return "отклонить", f"год {y}: после 1917 — вне скоупа (список будущего)"
    if SOVIET.search(title):
        return "отклонить", "советское издание — после 1917, вне скоупа"
    if NEWSPAPER.search(title):
        return "отклонить", "газета — класс исключён решением владельца 23.11.2026"
    if FINANCE.search(title):
        return "отклонить", "финансовая ведомость — класс исключён решением владельца 23.11.2026"
    if (r["Архив [авто]"] or "").startswith("Госкаталог") and MOSCOW.search(text):
        return "отклонить", "территория — Москва, не наши губернии"
    if stratum(r) in PASSED:
        return "принять", "слой прошёл выборочную проверку 23.11.2026"
    # Тома переписи 1897 г. нумеруются по губерниям: наши — 16 Калужская, 31 Пермская,
    # 40 Смоленская, 50 Ярославская. Нумерованный том другой губернии — не наш, хотя заголовок
    # серии «по Российской империи» читается как обзорный (найдено на выборке 23.11).
    m = CENSUS_VOL.search(title)
    if m and not any(o in title for o in OUR):
        n = int(m.group(1))
        if n in CENSUS_OURS:
            return "принять", f"том {n} переписи 1897 г. — {CENSUS_OURS[n]} губерния"
        return "отклонить", f"том {n} переписи 1897 г. — другая губерния"
    v, why = classify(title)
    fr = FOREIGN_REGION.search(title)
    if v in ("общая", "нет") and fr and not any(o in title for o in OUR):
        # Общеимперское издание, где чужой регион лишь перечислен рядом с нашими («51 губерния
        # … Царство Польское», «в Европейской и Азиатской России»), — наше; отклоняем только
        # ВЫПУСК, посвящённый чужому региону («Вып. 11 : Полесская полоса»).
        overview = OVERVIEW.search(title)
        if not overview or VOLUME_OF.search(title):
            return "отклонить", f"выпуск по другому региону: «{fr.group(0)}»"
    if v == "наша":
        return "принять", f"территория по заголовку: {why}"
    if v == "чужая":
        return "отклонить", f"чужая губерния: {why}"
    if v == "общая":
        return "принять", f"обзорный (межгубернский) источник: {why}"
    if (r["Архив [авто]"] or "") in REGIONAL and any(o in (r["Современные регионы"] or "") for o in OUR):
        return "принять", "территория по провенансу держателя"
    if re.search(r"Европейск\w* Росси|Российск\w* импери|Росси[ия]\b|всей России", title, re.I):
        return "принять", "обзорный источник по империи / Европейской России"
    if re.search(r"условн\w* знак", title, re.I):
        return "принять", "условные знаки — класс включён решением владельца (62 записи, 23.11)"
    reg = r["Современные регионы"] or ""
    if any(o in reg for o in OUR) and not re.search(r"малоярослав", title, re.I):
        return "принять", "территория по полю «Современные регионы»"
    return "владельцу", "территория не определяется ни по заголовку, ни по держателю"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig", newline="")))
    cand = [r for r in rows if r["Статус приёмки"] == "кандидат"]
    # точные дубли: та же ссылка и тот же заголовок, что у живой записи, созданной раньше
    # (у принятой записи — приоритет; среди кандидатов оставляем первый по порядку слепка)
    first: dict[tuple[str, str], str] = {}
    for r in sorted(rows, key=lambda x: (x["Статус приёмки"] != "принято")):
        if r["Статус приёмки"] == "отклонено" or not r["Ссылка на онлайн-архив"]:
            continue
        first.setdefault((r["Ссылка на онлайн-архив"], norm(r["Название источника"])), r["page_id"])
    out, tally = [], defaultdict(Counter)
    for r in cand:
        key = (r["Ссылка на онлайн-архив"], norm(r["Название источника"]))
        if r["Ссылка на онлайн-архив"] and first.get(key) not in (None, r["page_id"]):
            d, why = "отклонить", f"точный дубль записи {first[key]} (та же ссылка и заголовок)"
        else:
            d, why = decide(r)
        out.append({"page_id": r["page_id"], "слой": stratum(r), "решение": d, "причина": why,
                    "Название источника": r["Название источника"],
                    "Ссылка на онлайн-архив": r["Ссылка на онлайн-архив"]})
        tally[stratum(r)][d] += 1
    p = OUT / "reshenie.csv"
    with p.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    print(f"кандидатов: {len(cand)} → {p}")
    print("итого:", dict(Counter(o["решение"] for o in out)))
    for s, c in sorted(tally.items(), key=lambda x: -sum(x[1].values())):
        print(f"  {s}: {dict(c)}")
    print("причины отклонения:")
    for k, v in Counter(re.sub(r"\d{4}|[0-9a-f-]{36}", "N", o["причина"]).split(":")[0]
                        for o in out if o["решение"] == "отклонить").most_common():
        print(f"  {v:6} {k}")


if __name__ == "__main__":
    main()
