def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    apply = ap.parse_args().apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))
    pages = query_all(client, SERIES_DS)
    print(f"карточек серий: {len(pages)}\n")

    for spec in CARDS:
        hit = next((p for p in pages
                    if spec["match"].lower() in title_of(p).lower()), None)
        if hit:
            upd = {k: {"rich_text": rt(v)} for k, v in spec["f"].items() if is_empty(hit, k)}
            upd |= {k: {"number": v} for k, v in spec["num"].items() if is_empty(hit, k)}
            upd |= {k: {"select": {"name": v}} for k, v in spec["sel"].items()
                    if is_empty(hit, k)}
            print(f"ЕСТЬ   {title_of(hit)[:58]} → дозаполнить {len(upd)} полей")
            if upd and apply:
                retry(lambda: client.pages.update(page_id=hit["id"], properties=upd))
                print("       обновлена")
        else:
            n = 1 + len(spec["f"]) + len(spec["num"]) + len(spec["sel"])
            print(f"НЕТ    {spec['title'][:58]} → создать, полей {n}")
            if apply:
                props: dict = {"Название серии": {
                    "title": [{"type": "text", "text": {"content": spec["title"]}}]}}
                props |= {k: {"number": v} for k, v in spec["num"].items()}
                props |= {k: {"rich_text": rt(v)} for k, v in spec["f"].items()}
                props |= {k: {"select": {"name": v}} for k, v in spec["sel"].items()}
                page = retry(lambda: client.pages.create(
                    parent={"database_id": SERIES_DB}, properties=props))
                print(f"       СОЗДАНА {page['id']}")


if __name__ == "__main__":
    main()
