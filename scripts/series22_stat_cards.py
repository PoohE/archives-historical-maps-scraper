def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))
    cards = {title_of(x): x for x in query_all(c, SERIES_DS)}
    for name, fields in CARDS.items():
        card = cards.get(name)
        if not card:
            print(f"⚠️ карточка не найдена: {name}")
            continue
        props = {k: {"rich_text": rt(v)} for k, v in fields.items()}
        retry(lambda card=card, props=props: c.pages.update(page_id=card["id"], properties=props))
        print(f"заполнена: {name} ({len(fields)} полей)")


if __name__ == "__main__":
    main()
