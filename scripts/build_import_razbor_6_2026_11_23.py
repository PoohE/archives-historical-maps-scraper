def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    cols = next(csv.reader(SAMPLE.open(encoding="utf-8-sig")))
    REVIEW.mkdir(parents=True, exist_ok=True)
    out: list[dict] = []
    recs: list[dict] = []
    for r in ROWS:
        line = dict.fromkeys(cols, "")
        line["Название источника"] = r["title"]
        line["Ссылка на онлайн-архив"] = r["url"]
        line["Место хранения"] = r["archive"]
        line["Статус доступа"] = "Открытый доступ"
        line["Год создания (нижняя)"] = r["lo"]
        line["Год создания (верхняя)"] = r["hi"]
        if r["lo"] == r["hi"]:
            line["Год сведений"] = r["lo"]
        line["Год: источник значения"] = SRC
        if r["level"]:
            line["Административный уровень"] = r["level"]
            line["Административный уровень: источник значения"] = SRC
        line["Территория: источник значения"] = SRC
        line["Примечания"] = (
            "Серийный улов библиотек 13–16.11.2026; разбор группы «на разбор» 23.11.2026: "
            "год и состав сверены по карточке держателя вручную. " + r["note"]
            + " «Серия / массив» заполняется отдельным проходом атрибуции.")
        for col in SELECTS:
            if "," in str(line.get(col, "")):
                line[col] = str(line[col]).replace(",", " —")
        out.append(line)
        recs.append({"url": r["url"],
                     "relations": [{"property": "Архив хранения",
                                    "source_label": r["archive"]}],
                     "territory_hints": [r["terr"]] if r["terr"] else []})

    with (REVIEW / "notion_import.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(out)
    (REVIEW / "export_review.json").write_text(
        json.dumps({"records": recs}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"строк CSV: {len(out)} | relations: {len(recs)}")
    for r in out:
        print(f"  {r['Год создания (нижняя)']}–{r['Год создания (верхняя)']} | "
              f"{r['Название источника'][:70]}")
    print(f"пакет: {REVIEW}")


if __name__ == "__main__":
    main()
