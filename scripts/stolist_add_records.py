# производная запись каталога, которую нужно привязать к серии
DERIVED = "4000ba89-eabe-81ca-97e3-c3dd8bfc3e8d"  # заполняется в apply по поиску, см. find_derived()
DERIVED_TITLE = "Географическая карта Пермской губернии Чердынского уезда"


def props_for(rec):
    из_схемы = {}
    for k, v in rec.items():
        if k.startswith("_"):
            continue
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            из_схемы[k] = {"number": v}
        elif k in ("Нулевой меридиан", "Техника исполнения", "Административный уровень", "Язык",
                   "DC Type", "Статус доступа", "Статус приёмки", "Автор внесения",
                   "Картографическая проекция"):
            из_схемы[k] = {"select": {"name": v}}
        elif k == "Название источника":
            из_схемы[k] = {"title": rt(v)}
        elif k == "Ссылка на онлайн-архив":
            из_схемы[k] = {"url": v}
        else:
            из_схемы[k] = {"rich_text": rt(v)}
    из_схемы["Архив хранения"] = {"relation": [{"id": i} for i in rec["_arch"]]}
    из_схемы["Тип источника"] = {"relation": [{"id": i} for i in rec["_type"]]}
    из_схемы["Охватываемая территория"] = {"relation": [{"id": i} for i in rec["_terr"]]}
    из_схемы["Серия / массив"] = {"relation": [{"id": SERIES}]}
    if rec["_obj"]:
        из_схемы["Типы отображаемых объектов"] = {"relation": [{"id": i} for i in rec["_obj"]]}
    return из_схемы


def client_():
    load_env(ENV_PATH)
    from notion_client import Client
    return Client(auth=env("NOTION_TOKEN", required=True))


def find_derived(client):
    res = retry(client.search, query=DERIVED_TITLE, filter={"property": "object", "value": "page"})
    out = []
    for p in res.get("results", []):
        t = p.get("properties", {}).get("Название источника", {}).get("title", [])
        name = "".join(x.get("plain_text", "") for x in t)
        if DERIVED_TITLE in name:
            out.append((p["id"], name))
    return out


def main():
    fix_stdout()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("mode", choices=["plan", "apply", "verify"])
    args = ap.parse_args()
    logger = log("stolist_add_records")
    outdir = Path(__file__).resolve().parent.parent / "output" / "stolist_records_2026-11-06"
    outdir.mkdir(parents=True, exist_ok=True)

    if args.mode == "plan":
        for r in RECORDS:
            print("-", r["Название источника"][:110])
            print("   архив", r["_arch"], "тип", r["_type"], "терр", len(r["_terr"]), "объекты", len(r["_obj"]))
        print(f"Всего к созданию: {len(RECORDS)}; плюс привязка производной «{DERIVED_TITLE}…» к серии")
        return

    client = client_()
    done = outdir / "created.jsonl"
    if args.mode == "apply":
        existing = {json.loads(x)["title"] for x in done.read_text(encoding="utf-8").splitlines() if x.strip()} if done.exists() else set()
        with done.open("a", encoding="utf-8") as jl:
            for r in RECORDS:
                if r["Название источника"] in existing:
                    logger.info("пропуск (уже создано): %s", r["Название источника"][:70])
                    continue
                page = retry(client.pages.create, parent={"database_id": CATALOG}, properties=props_for(r))
                jl.write(json.dumps({"title": r["Название источника"], "id": page["id"]}, ensure_ascii=False) + "\n")
                jl.flush()
                logger.info("создано: %s", r["Название источника"][:70])
                time.sleep(SLEEP)
        for pid, name in find_derived(client):
            props = retry(client.pages.retrieve, page_id=pid)["properties"]
            rel = [x["id"] for x in props.get("Серия / массив", {}).get("relation", [])]
            if SERIES not in rel:
                retry(client.pages.update, page_id=pid,
                      properties={"Серия / массив": {"relation": [{"id": i} for i in rel + [SERIES]]}})
                logger.info("привязана производная: %s", name[:70])
            else:
                logger.info("производная уже привязана: %s", name[:70])
        return

    bad = 0
    for line in done.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        props = retry(client.pages.retrieve, page_id=rec["id"])["properties"]
        rel = [x["id"] for x in props.get("Серия / массив", {}).get("relation", [])]
        ok = SERIES in rel and props.get("Статус приёмки", {}).get("select", {}).get("name") == "кандидат"
        bad += not ok
        print("OK " if ok else "НЕТ", rec["title"][:80])
        time.sleep(SLEEP)
    print(f"verify: расхождений {bad}")


if __name__ == "__main__":
    main()
