def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    existing = [x for x in query_all(c, SERIES_DS) if NAME[:30] in title_of(x)]
    if existing:
        card = existing[0]
        print(f"карточка уже есть: {title_of(card)}")
    elif not args.apply:
        print(f"карточки нет — будет создана: «{NAME}»")
        card = None
    else:
        props = {
            "Название серии": {"title": [{"text": {"content": NAME}}]},
            "Хронология нижняя": {"number": 1893},
            "Хронология верхняя": {"number": 1925},
        }
        for k, v in FIELDS.items():
            if k != "Название серии":
                props[k] = {"rich_text": rt(v)}
        card = retry(lambda: c.pages.create(parent={"database_id": SERIES_DB}, properties=props))
        print(f"карточка создана: {NAME}")

    # ⚠️ Живой запрос к каталогу обрывается на 10 000 записях (их 112 202),
    # поэтому отбор идёт ОФЛАЙН по выгрузке, а по сети только обновление.
    import json

    base = BASELINE
    if not base.exists():
        sys.exit(f"нет выгрузки каталога: {base}")
    pages = []
    for line in base.open(encoding="utf-8"):
        if not line.strip():
            continue
        rec = json.loads(line)
        f = rec.get("fields") or {}
        t = str(f.get("Название источника") or "")
        if MATCH.search(t):
            pages.append((rec["page_id"], t))
    print(f"записей каталога под серию (офлайн-отбор): {len(pages)}")

    if not args.apply or card is None:
        for _, ttl in pages[:12]:
            print(f"   → {ttl[:100]}")
        print("\nбез --apply ничего не записано")
        return

    n = skipped = 0
    for pid, _ in pages:
        pg = retry(lambda pid=pid: c.pages.retrieve(page_id=pid))
        rel = (pg["properties"].get("Серия / массив") or {}).get("relation") or []
        if any(x["id"] == card["id"] for x in rel):
            skipped += 1
            continue
        retry(
            lambda pid=pid, rel=rel: c.pages.update(
                page_id=pid,
                properties={"Серия / массив": {"relation": rel + [{"id": card["id"]}]}},
            )
        )
        n += 1
        if n % 10 == 0:
            print(f"  связано {n}…", flush=True)
    print(f"связано записей: {n}; уже были связаны: {skipped}")


if __name__ == "__main__":
    main()
