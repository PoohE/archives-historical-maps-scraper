def rt(text: str) -> list[dict]:
    """rich_text с нарезкой по 1900 знаков (лимит Notion ~2000 на объект)."""
    return [{"type": "text", "text": {"content": text[i:i + 1900]}}
            for i in range(0, len(text), 1900)] or [{"type": "text", "text": {"content": ""}}]


def title_of(page: dict) -> str:
    for v in page["properties"].values():
        if v.get("type") == "title":
            return "".join(r["plain_text"] for r in v["title"])
    return ""


def is_empty(page: dict, prop: str) -> bool:
    v = page["properties"].get(prop)
    if not v:
        return True
    if v["type"] == "rich_text":
        return not "".join(r["plain_text"] for r in v["rich_text"]).strip()
    if v["type"] == "select":
        return v["select"] is None
    if v["type"] == "number":
        return v["number"] is None
    return False


def query_all(client: Client, ds: str, **extra) -> list[dict]:
    out, cursor = [], None
    while True:
        body: dict = {"page_size": 100, **extra}
        if cursor:
            body["start_cursor"] = cursor
        resp = retry(lambda: client.data_sources.query(data_source_id=ds, **body))
        out.extend(resp["results"])
        if not resp.get("has_more"):
            break
        cursor = resp["next_cursor"]
    return out


def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    args = ap.parse_args()
    apply = args.apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))

    series = {title_of(p): p for p in query_all(client, SERIES_DS)}
    print(f"карточек серий: {len(series)}")

    # --- 1. карточка серии 9
    s9 = series.get(S9_TITLE)
    if s9:
        print(f"серия 9: карточка есть, {s9['id']}")
    elif apply:
        props: dict = {"Название серии": {"title": [{"type": "text",
                                                     "text": {"content": S9_TITLE}}]},
                       "Хронология нижняя": {"number": 1842},
                       "Хронология верхняя": {"number": 1914}}
        for k, v in S9_FIELDS.items():
            props[k] = {"rich_text": rt(v)}
        for k, v in S9_SELECTS.items():
            props[k] = {"select": {"name": v}}
        s9 = retry(lambda: client.pages.create(
            parent={"database_id": SERIES_DB}, properties=props))
        series[S9_TITLE] = s9
        print(f"серия 9: СОЗДАНА карточка {s9['id']}, заполнено полей "
              f"{len(S9_FIELDS) + len(S9_SELECTS) + 2}")
    else:
        print(f"серия 9: карточки НЕТ → будет создана, поля: "
              f"{', '.join(list(S9_FIELDS) + list(S9_SELECTS))}, "
              f"Хронология нижняя 1842, верхняя 1914")

    # --- 2. пустые поля серии 10
    s10 = series.get(S10_TITLE)
    if not s10:
        print(f"!! карточка «{S10_TITLE}» не найдена")
    else:
        upd = {k: {"rich_text": rt(v)} for k, v in S10_FILL.items() if is_empty(s10, k)}
        skip = [k for k in S10_FILL if k not in upd]
        print(f"серия 10: заполнить пустых полей {len(upd)} "
              f"({', '.join(upd) or '—'}); занятых не трогаем: {', '.join(skip) or '—'}")
        if upd and apply:
            retry(lambda: client.pages.update(page_id=s10["id"], properties=upd))
            print("серия 10: обновлена")

    # --- 3. записи без серии
    new = query_all(client, CATALOG_DS,
                    filter={"timestamp": "created_time",
                            "created_time": {"on_or_after": "2026-11-01"}})
    done = 0
    for page in new:
        name = title_of(page)
        for key, targets in ORPHANS.items():
            if not name.startswith(key[:60]):
                continue
            cur = page["properties"].get(SERIES_FIELD, {}).get("relation") or []
            if cur:
                print(f"  пропуск (серия уже есть): {name[:70]}")
                break
            ids = []
            for t in targets:
                if t in series:
                    ids.append({"id": series[t]["id"]})
                else:
                    print(f"  !! нет карточки серии «{t}» — связь не поставлена")
            print(f"  {'привязка' if apply else 'план'}: {name[:70]}")
            print(f"      → {'; '.join(t for t in targets if t in series)}")
            if apply and ids:
                retry(lambda: client.pages.update(
                    page_id=page["id"], properties={SERIES_FIELD: {"relation": ids}}))
                done += 1
            break
    print(f"\nзаписей привязано: {done}" if apply else "\n(прогон плановый, записи не менялись)")


if __name__ == "__main__":
    main()
