def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--links", action="store_true")
    args = ap.parse_args()

    if args.links:
        if LOCK.exists():
            sys.exit(f"уже идёт прогон ({LOCK.name}) — не запускаю второй")
        busy = [p.name for p in OTHER_LOCKS if p.exists()]
        if busy:
            sys.exit(
                "идёт другой прогон привязки: "
                + ", ".join(busy)
                + " — перекрывающиеся процессы уже давали лавину 429, жду"
            )

    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    existing = [x for x in query_all(c, SERIES_DS) if "горнозаводского Урала" in title_of(x)]
    card = existing[0] if existing else None
    props = {
        k: ({"title": rt(v)} if k == "Название серии" else {"rich_text": rt(v)})
        for k, v in FIELDS.items()
    }
    if card:
        print(f"карточка есть: {title_of(card)}")
        if args.apply:
            retry(lambda: c.pages.update(page_id=card["id"], properties=props))
            print("поля перезаписаны")
    elif args.apply:
        card = retry(
            lambda: c.pages.create(parent={"database_id": SERIES_DB}, properties=props)
        )
        print(f"создана карточка: {NAME}")
    else:
        print(f"карточки нет — будет создана: {NAME}")

    rows = [json.loads(ln) for ln in LINKS.open(encoding="utf-8") if ln.strip()]
    pages = [r["page_id"] for r in rows if r["page_id"]]
    print(f"записей каталога под привязку: {len(pages)} (без page_id: {len(rows) - len(pages)})")
    if not (args.apply and args.links) or card is None:
        print("привязка не выполнялась (нужен --apply --links)")
        return

    LOCK.write_text("series24", encoding="utf-8")
    try:
        n = skipped = 0
        for i, pid in enumerate(pages, 1):
            pg = retry(lambda pid=pid: c.pages.retrieve(page_id=pid))
            rel = (pg["properties"].get("Серия / массив") or {}).get("relation") or []
            if any(x["id"] == card["id"] for x in rel):
                skipped += 1
                continue
            retry(
                lambda pid=pid, rel=rel: c.pages.update(
                    page_id=pid,
                    properties={
                        "Серия / массив": {"relation": rel + [{"id": card["id"]}]}
                    },
                )
            )
            n += 1
            if i % 100 == 0:
                print(f"  {i}/{len(pages)}: связано {n}, уже были {skipped}", flush=True)
        print(f"ИТОГО связано: {n}; уже были связаны: {skipped}")
    finally:
        LOCK.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
