# -*- coding: utf-8 -*-
"""Смысловой гейт улова фондового прогона РГИА по статистическим фондам.

Зачем. Отбор по шифру (`rgia_stat_funds.py`) отвечает на вопрос «из нужного ли фонда дело»,
но не на вопрос «статистика ли это». Проверка 16.11.2026 на первых 3 847 делах показала, что
улов наполовину посторонний:
  * Ф. 37 — «Отделение касс горного ведомства», то есть бухгалтерия департамента;
  * Ф. 20 — «Отношение Канцелярии… об уведомлении о поступлении» — делопроизводственная переписка;
  * Ф. 593 — «О перезалоге имения СМОЛЕНСКОЙ А. И.» — ФАМИЛИЯ, а не губерния: та же ловушка
    склонений, что уже ловилась на «Краснуфимском» и «Ярославля».
Поэтому нужен второй гейт — по смыслу заголовка.

Три решения на дело:
  * «берём» — есть признак статистического или учётного материала;
  * «на человека» — признак есть, но территория сомнительна (однофамилец, чужая губерния);
  * «отсев» — бухгалтерия, переписка, личные дела, ссуды и залоги.
Отсев НЕ удаляется, а пишется с причиной (правило проекта: отсев — это знание о границах
корпуса).

  python gate_rgia_stat.py
"""

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, r"D:\IG Dropbox\Andy PoohV\Project\Claude\scripts\lib")
from common import fix_stdout  # noqa: E402

SRC = ROOT / "output" / "rgia_stat_funds" / "fund_hits.jsonl"
OUT = ROOT / "output" / "rgia_stat_funds"

# Признак статистического/учётного материала — то, ради чего фонды и выявлялись
KEEP = re.compile(
    r"статистическ\w+ (сведени|таблиц|данн|материал|обзор)|ведомост\w+|"
    r"свод\w*\s+(данн|сведен)|материал\w+ обследован|перепис\w+|"
    r"сведени\w+ о (числ|количеств|состоян|населен|посев|урожа|фабрик|заводах|училищ|школ)|"
    r"отчёт\w*\s+о состоянии|обзор губерни|итоги|подворн\w+|"
    r"карт\w+|план\w+|атлас|чертеж|чертёж|съёмк|съемк", re.I)

# Явный не-статистический материал: бухгалтерия, переписка, частные дела
DROP = {
    "бухгалтерия и кассы": re.compile(
        r"касс\w+|сметн\w+ назначен|ассигнован|авансов\w+|о выдаче денег|"
        r"о расходовании|жалован|пенси|наградн", re.I),
    "делопроизводственная переписка": re.compile(
        r"^отношени|переписка (с|о)|о препровождении|об уведомлении|"
        r"о доставлении сведений по запросу|циркуляр", re.I),
    "ссуды, залоги, частные имения": re.compile(
        r"перезалог|о залоге|о ссуде|об отсрочке платеж|о продаже имения|"
        r"прошени\w+ (дворян|крестьян)", re.I),
    "личный состав": re.compile(r"о службе|формулярн\w+ список|об определении на службу", re.I),
}

# Ловушка однофамильцев: губерния в заголовке стоит как ФАМИЛИЯ
SURNAME = re.compile(
    r"(смоленск|ярославск|пермск|калужск)\w*\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.|"
    r"(смоленск|ярославск|пермск|калужск)ой\s+[А-ЯЁ][а-яё]+(ой|ы|е)\b", re.I)

GUB = re.compile(r"калужск|смоленск|ярославск|пермск", re.I)

# ⚠️ ЗАГОЛОВКИ РГИА ТРЁХЧАСТНЫЕ: «<фонд>. <структурная часть>. <содержание дела>».
# Решение принимается ТОЛЬКО по содержанию: 16.11.2026 выяснилось, что слово «касс» в
# «Отделение касс горного ведомства» — название отделения, и отсев по нему выбрасывал
# настоящие статистические дела, а попадание таких дел в «берём» было правильным.
STRUCT = re.compile(
    r"^(горный департамент|центральный статистический комитет|департамент[а-яё ]*|"
    r"министерств[оа][а-яё ]*|главное управление[а-яё ]*|лесной департамент|"
    r"отделени[ея][а-яё ]*|бухгалтери[яи]|счетное отделение|\d+\s*стол|"
    r"[ivx]+ отделение|заводы частных владельцев|канцеляри[яи])[^.]*$", re.I)


def body(title: str) -> str:
    """Содержание дела: заголовок без названия фонда и структурных частей."""
    segs = [s.strip() for s in re.split(r"(?<=[а-яё\)])\.\s+", title) if s.strip()]
    kept = [s for s in segs if not STRUCT.match(s)]
    return " ".join(kept) if kept else title


def main() -> None:
    fix_stdout()
    if not SRC.exists():
        sys.exit(f"нет улова: {SRC}")
    rows = [json.loads(x) for x in SRC.open(encoding="utf-8") if x.strip()]
    print(f"дел на входе: {len(rows)}")

    buckets: dict[str, list] = collections.defaultdict(list)
    stat: collections.Counter = collections.Counter()
    seen: set[tuple] = set()
    for r in rows:
        full = (r.get("title") or "").strip()
        title = body(full)          # решение — по содержанию дела, не по названию фонда
        code = (r.get("fund_code") or "").strip()
        key = (code, full[:70])
        if key in seen:
            stat["дубль по шифру+заголовку"] += 1
            continue
        seen.add(key)

        reason = next((lab for lab, rx in DROP.items() if rx.search(title)), None)
        if reason:
            # ⚠️ КОНФЛИКТ ПРИЗНАКОВ РЕШАЕТ ЧЕЛОВЕК (16.11.2026): если в содержании есть и
            # признак отсева, и признак статистики, молча выбрасывать нельзя. Проверка на
            # 146 делах «бухгалтерии» дала 16 таких, и среди них «Счёт кассы, сведения о
            # количестве и сортах приготовленных металлов и о продаже железа» — это
            # производственная статистика завода, а не касса.
            if KEEP.search(title):
                stat["на человека: конфликт признаков (отсев + статистика)"] += 1
                buckets["на человека"].append({
                    **r, "решение": "на человека",
                    "причина": f"конфликт: {reason} + признак статистики",
                    "содержание": title[:200]})
                continue
            stat[f"отсев: {reason}"] += 1
            buckets["отсев"].append({**r, "решение": "отсев", "причина": reason,
                                     "содержание": title[:200]})
            continue
        if SURNAME.search(title):
            stat["на человека: губерния похожа на фамилию"] += 1
            buckets["на человека"].append({**r, "решение": "на человека",
                                           "причина": "губерния в заголовке похожа на фамилию"})
            continue
        if not KEEP.search(title):
            stat["отсев: нет признака статистики или картографии"] += 1
            buckets["отсев"].append({**r, "решение": "отсев",
                                     "причина": "нет признака статистики или картографии"})
            continue
        if not GUB.search(title):
            stat["на человека: наша губерния не названа"] += 1
            buckets["на человека"].append({**r, "решение": "на человека",
                                           "причина": "губерния не названа в заголовке"})
            continue
        stat["берём"] += 1
        buckets["берём"].append({**r, "решение": "берём", "содержание": title[:200]})

    print("\nРЕШЕНИЯ:")
    for k, v in stat.most_common():
        print(f"  {v:6d}  {k}")

    for name, rows_ in buckets.items():
        path = OUT / f"gate_{name.replace(' ', '_')}.jsonl"
        with path.open("w", encoding="utf-8") as f:
            for row in rows_:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"→ {path.name}: {len(rows_)}")

    byf = collections.Counter()
    for r in buckets["берём"]:
        m = re.search(r"0*(1290|573|593|733|744|20|23|37|44|350)\b", r.get("fund_code") or "")
        if m:
            byf[m.group(1)] += 1
    print("\n«берём» по фондам:", dict(byf.most_common()))
    print("\nпримеры «берём»:")
    for r in buckets["берём"][:12]:
        print(f"  {r.get('fund_code','')[:24]:26} {(r.get('title') or '')[:94]}")


if __name__ == "__main__":
    main()
