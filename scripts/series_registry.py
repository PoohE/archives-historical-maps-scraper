def series_nums(seriya: str) -> list[str]:
    """Из строки «серия 8 — …; серия 13 — …» вытащить номера: ['8', '13'].

    Отдельно распознаются «серия 5а» и группа «знаки и инструкции».
    """
    import re

    out: list[str] = []
    for m in re.finditer(r"серия\s+(\d+а?)", seriya or ""):
        out.append(m.group(1))
    if "знаки и инструкции" in (seriya or ""):
        out.append("знаки")
    seen: list[str] = []
    for s in out:
        if s not in seen:
            seen.append(s)
    return seen


