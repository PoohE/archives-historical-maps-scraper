def territory_gate_selftest() -> int:
    """Прогон эталонного набора. Возвращает число несовпадений."""
    bad = 0
    for text, want in CASES:
        got, why = classify(text)
        if got != want:
            bad += 1
            print(f"  [x] ждали {want}, получили {got} ({why}) :: {text}")
    print(f"эталон территориального гейта: {len(CASES) - bad}/{len(CASES)} совпало")
    return bad


