GUB_WORD = r"\w*\s+(?:губерн|област|кра[йяею]|наместнич|уезд)"
GUB_ENUM = r"\w*\s+(?:и|,)\s+\S{3,20}\s+(?:губерн|област)"


def _city_pat(name: str) -> str:
    """Шаблон города с учётом склонения.

    ⚠️ Прежняя версия брала название целиком и позволяла дописать до трёх букв.
    Это ломается там, где при склонении ПОСЛЕДНЯЯ буква исчезает:
    «Ярославль → Ярославля», «Калуга → Калуги», «Пермь → Перми» — то есть на
    губернских центрах трёх наших четырёх губерний (найдено 10.11.2026 на записи
    «План города Ярославля»). Поэтому у слов на «ь», «а», «я» берём основу.
    Основу короче четырёх букв не трогаем: «Оса» → «Ос» ловило бы «основание».
    """
    stem = name
    if name[-1] in "ьая" and len(name) - 1 >= 4:
        stem = name[:-1]
    return r"\b" + re.escape(stem) + r"[а-яё]{0,3}\b"


def _city_hit(name: str, text: str) -> bool:
    """Город опознан. Регистрозависимо: топоним с заглавной, обычное слово — нет."""
    pat = _city_pat(name)
    if name in AMBIG:
        return bool(
            re.search(CONTEXT + r"\s+" + pat, text)
            or re.search(pat + r"\s*,?\s*" + CONTEXT, text)
        )
    return bool(re.search(pat, text))


def _mask(title: str) -> str:
    t = re.sub(r"\s+", " ", title or "")
    for fp in FALSE_POSITIVE:
        t = re.sub(fp, " [омоним] ", t, flags=re.I)
    return t


def _gub_hits(masked: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for gub, d in OUR.items():
        stem = gub[:-2]
        if re.search(stem + GUB_WORD, masked, re.I):
            out.append((gub, f"{gub} губерния названа прямо"))
            continue
        if re.search(stem + GUB_ENUM, masked, re.I):
            out.append((gub, f"{gub} в перечислении губерний"))
            continue
        found = False
        for u in d["uezd"]:
            if re.search(re.escape(u) + r"(?:ий|ого|ом|ому|ая|ой)?\s+уезд", masked, re.I):
                out.append((gub, f"{u}ий уезд -> {gub} губерния"))
                found = True
                break
        if found:
            continue
        for c in d["cities"]:
            if _city_hit(c, masked):
                out.append((gub, f"город/топоним «{c}» -> {gub}"))
                break
    return out


def classify(title: str) -> tuple[str, str]:
    """Вернуть (решение, пояснение)."""
    if not (title or "").strip():
        return "нет", "заголовок пуст"
    masked = _mask(title)

    hits = _gub_hits(masked)
    if hits:
        return "наша", "; ".join(dict.fromkeys(w for _, w in hits))

    for fg in FOREIGN_GUB:
        # ⚠️ граница слова обязательна: без неё «Красноуфимского уезда» (Пермская
        # губерния!) ловился как «Уфимская», и два плана Суксунского завода и
        # Алтыновской волости были помечены чужими. Найдено 10.11.2026 при
        # поимённой проверке 19 «чужих» записей каталога.
        if re.search(
            r"\b" + re.escape(fg) + r"\w*\s+(?:губерн|област|кра[йяею]|уезд|наместнич)",
            masked,
            re.I,
        ):
            return "чужая", f"названа чужая территория: {fg}…"

    for g in GENERAL:
        if re.search(re.escape(g), masked, re.I):
            return "общая", f"обзорная карта: «{g}»"

    return "нет", "территория в заголовке не названа"


def our_gubernii(title: str) -> list[str]:
    """Список наших губерний, опознанных в заголовке (может быть несколько)."""
    return [g for g, _ in _gub_hits(_mask(title))]


# --- рубрика-префикс карточки РГБ -------------------------------------------
# В записи РГБ заголовок часто начинается ГЕОГРАФИЧЕСКОЙ РУБРИКОЙ, отделённой
# «. - »: «Крымский полуостров. - Карта Крыма Шуберта…». Это и есть территория
# по мнению каталогизатора. Поймано 08.11.2026: 173 из 698 записей без территории
# в самом названии имеют такую рубрику, и почти все они — чужие.
PERSON = re.compile(r"^[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?,\s*[А-ЯЁ][а-яё]+")
# Рубрика-учреждение, а не место: «Россия. Законы и постановления»,
# «Омский военный округ. Штаб…» — территорию из неё выводить нельзя.
ORG_RUBRIC = re.compile(
    r"(Законы|постановлени|Археографическ|комисси|Штаб|Командующий|Министерств|"
    r"Управлени|Департамент|Академия|Общество|Комитет|Атлас|Сенат)",
    re.I,
)


def rubric(title: str) -> str:
    """Географическая рубрика карточки или пустая строка."""
    parts = re.split(r"\.\s+-\s+", (title or "").strip(), maxsplit=1)
    if len(parts) != 2:
        return ""
    p = parts[0].strip()
    if len(p) > 60 or ":" in p or PERSON.match(p):
        return ""
    return p


def rubric_verdict(title: str) -> tuple[str, str]:
    """Решение по рубрике: ('наша'|'чужая'|'учреждение'|'', пояснение)."""
    p = rubric(title)
    if not p:
        return "", ""
    if ORG_RUBRIC.search(p):
        return "учреждение", f"рубрика «{p}» — учреждение или форма, не территория"
    if _gub_hits(_mask(p)):
        return "наша", f"наша территория по рубрике карточки: «{p}»"
    return "чужая", f"чужая территория по рубрике карточки: «{p}»"


