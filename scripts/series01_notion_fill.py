def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    apply = ap.parse_args().apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))
    cards = {title_of(p): p for p in query_all(client, SERIES_DS)}
    page = cards.get(TITLE)
    if not page:
        hit = [t for t in cards if "исцов" in t]
        print(f"!! карточка не найдена. Похожие: {hit}")
        return

    upd = {k: {"rich_text": rt(v)} for k, v in FIELDS.items() if is_empty(page, k)}
    skip = [k for k in FIELDS if k not in upd]
    print(f"серия 1: заполнить пустых полей {len(upd)}: {', '.join(upd) or '—'}")
    print(f"         занятых не трогаем: {', '.join(skip) or '—'}")
    if upd and apply:
        retry(lambda: client.pages.update(page_id=page["id"], properties=upd))
        print("серия 1: обновлена")


if __name__ == "__main__":
    main()
