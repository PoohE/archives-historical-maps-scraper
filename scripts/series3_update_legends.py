def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    mode = sys.argv[1] if len(sys.argv) > 1 else "plan"

    client = Client(auth=env("NOTION_TOKEN"))
    page = retry(lambda: client.pages.retrieve(SERIES3))
    cur = page["properties"].get(FIELD, {}).get("rich_text", [])
    cur_text = "".join(r["plain_text"] for r in cur)
    print(f"режим: {mode}")
    print(f"текущее значение ({len(cur_text)} знаков):\n{cur_text[:600]}\n...")

    if mode == "apply":
        retry(
            lambda: client.pages.update(
                SERIES3, properties={FIELD: {"rich_text": rt(NEW)}}
            )
        )
        print(f"\nЗАПИСАНО {len(NEW)} знаков")
    elif mode == "verify":
        ok = "4 июня 1838" in cur_text and "1-го Отделения" in cur_text
        print(f"\nсверка: {'OK' if ok else 'РАСХОЖДЕНИЕ'}")
        if not ok:
            print("  ожидалось «4 июня 1838» и «1-го Отделения»")


if __name__ == "__main__":
    main()
