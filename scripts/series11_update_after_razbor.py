def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    apply = ap.parse_args().apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))
    page = next((p for p in query_all(client, SERIES_DS)
                 if TITLE_MATCH in title_of(p)), None)
    if not page:
        print("!! карточка «Атласы Менде» не найдена")
        return

    upd = {k: {"rich_text": rt(v)} for k, v in OVERWRITE.items()}
    add = {k: {"rich_text": rt(v)} for k, v in APPEND_ONLY.items() if is_empty(page, k)}
    print(f"карточка: {title_of(page)} ({page['id']})")
    print(f"  перезаписать по разбору: {len(upd)} полей — {', '.join(upd)}")
    print(f"  дозаполнить пустые:      {len(add)} полей — {', '.join(add) or '—'}")
    if apply:
        retry(lambda: client.pages.update(page_id=page["id"], properties=upd | add))
        print("  обновлена")


if __name__ == "__main__":
    main()
