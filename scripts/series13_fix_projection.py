"""Поправка карточки серии 13: понизить статус атрибуции проекции.

08.11.2026 я записал в карточку равноугольную коническую проекцию Ламберта с параметрами
как установленную величину, с оговоркой «у Глушкова — проекция Гаусса». Проверка показала,
что это перевёрнутый приоритет источников:

  * «проекция Гаусса» — Глушков 2007, с. 195 (монография по истории военной картографии,
    со ссылкой на приказ Генерального штаба № 213 от 28.07.1833 о составлении карт России
    «преимущественно в проекции Гаусса»);
  * «Ламберта, стандартные параллели 45° и 59°, центральный меридиан 10° к востоку
    от Пулкова» — ckit.ru, ЛЮБИТЕЛЬСКИЙ сайт, без ссылки на выходные данные листа
    или ведомственную инструкцию.

По правилу проекта любительский сетевой источник не может перевешивать монографию.
Пока лист с выходными данными не прочитан, корректная запись — «источники расходятся».

  python series13_fix_projection.py --plan | --apply
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(r"D:\IG Dropbox\Andy PoohV\Project\Claude\scripts\lib")))

from common import env, fix_stdout, load_env  # noqa: E402
from mezh_batch_tag import ENV_PATH, retry  # noqa: E402
from notion_client import Client  # noqa: E402
from series910_notion_link import SERIES_DS, query_all, rt, title_of  # noqa: E402

OLD = (
    "ПРОЕКЦИЯ — равноугольная коническая ЛАМБЕРТА (у Глушкова «проекция Гаусса»): "
    "стандартные параллели 45° и 59°, центральный меридиан 10° к востоку от Пулково = "
    "40°19′30″ в.д. от Гринвича, исходная широта 52°30′; сетка в Пулковской системе. "
    "⚠️ Эти параметры позволяют АВТОМАТИЧЕСКУЮ привязку по рамке — в отличие от проекции "
    "Бонна у Шуберта и трёхвёрстки."
)
NEW = (
    "⚠️ ПРОЕКЦИЯ — ИСТОЧНИКИ РАСХОДЯТСЯ, вопрос НЕ РЕШЁН. (1) «Проекция Гаусса» — Глушков "
    "2007, с. 195; согласуется с приказом Генерального штаба № 213 от 28.07.1833 "
    "о составлении карт России «преимущественно в проекции Гаусса». (2) Равноугольная "
    "коническая ЛАМБЕРТА со стандартными параллелями 45° и 59°, центральным меридианом "
    "10° к востоку от Пулкова (= 40°19′30″ в.д. от Гринвича) и исходной широтой 52°30′ — "
    "эта атрибуция встречается ТОЛЬКО на любительском сайте ckit.ru, без ссылки на выходные "
    "данные листа или ведомственную инструкцию. Монография перевешивает сетевой источник, "
    "поэтому до чтения рамки листа с выходными данными в каталоге писать «не установлено». "
    "ЕСЛИ параметры Ламберта подтвердятся, карта получит важное преимущество: привязка "
    "по рамке станет автоматической, в отличие от проекции Бонна у Шуберта и трёхвёрстки. "
    "Это стоит проверить в первую очередь — цена вопроса высокая."
)


def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan", action="store_true")
    apply = ap.parse_args().apply

    load_env(ENV_PATH)
    client = Client(auth=env("NOTION_TOKEN"))
    page = next((p for p in query_all(client, SERIES_DS)
                 if "Стрельбиц" in title_of(p)), None)
    if not page:
        print("!! карточка не найдена")
        return

    field = "Отображаемые объекты (детально)"
    cur = "".join(r["plain_text"] for r in page["properties"][field]["rich_text"])
    if OLD not in cur:
        print("!! прежняя формулировка не найдена дословно — проверить вручную")
        return
    new = cur.replace(OLD, NEW, 1)
    print(f"карточка: {title_of(page)}")
    print(f"  было {len(cur)} знаков → станет {len(new)}")
    if apply:
        retry(lambda: client.pages.update(
            page_id=page["id"], properties={field: {"rich_text": rt(new)}}))
        print("  обновлена: атрибуция проекции понижена до «источники расходятся»")


if __name__ == "__main__":
    main()
