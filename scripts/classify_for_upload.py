def answer_text(message) -> str:
    """Текст ответа модели.

    ⚠️ У моделей с размышлением первым идёт ThinkingBlock, у которого нет `.text`
    (поймано на первом же прогоне pilot). Берём первый блок типа "text".
    """
    for block in message.content:
        if getattr(block, "type", None) == "text":
            return block.text.strip()
    raise ValueError("в ответе модели нет текстового блока")


def strip_fence(txt: str) -> str:
    if txt.startswith("```"):
        txt = txt.split("```")[1]
        if txt.startswith("json"):
            txt = txt[4:]
    return txt.strip()


