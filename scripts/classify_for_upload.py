def ask(client, items: list[tuple[int, str, str]]) -> list[dict]:
    """Один синхронный запрос по пачке заголовков (используется в pilot)."""
    body = "\n".join(
        f'{i}. ЗАГОЛОВОК: {t}' + (f'\n   ФОНД/СЕРИЯ: {c[:120]}' if c else '')
        for i, t, c in items
    )
    msg = client.messages.create(
        model=MODEL, max_tokens=8000, system=SYSTEM,
        messages=[{"role": "user", "content": body}],
    )
    return json.loads(strip_fence(answer_text(msg)))


def pilot() -> None:
    load_env()
    client = anthropic_client()
    items = [(i, t, GOLD_CTX.get(i, "")) for i, (t, _, _) in enumerate(GOLD)]
    got = {}
    for k in range(0, len(items), PER_REQ):
        for r in ask(client, items[k:k + PER_REQ]):
            got[int(r["i"])] = r

    ok_c = ok_l = 0
    print(f"{'#':>3s} {'класс':>11s} {'ожид':>11s} {'уровень':>11s} {'ожид':>11s}  заголовок")
    for i, (t, ec, el) in enumerate(GOLD):
        r = got.get(i, {})
        gc, gl = str(r.get("class")), str(r.get("level"))
        ok_c += gc == ec
        ok_l += gl == el
        mark = "" if (gc == ec and gl == el) else "  <<<"
        print(f"{i:3d} {gc:>11s} {ec:>11s} {gl:>11s} {el:>11s}  {t[:52]}{mark}")
    n = len(GOLD)
    print(f"\nКЛАСС: {ok_c}/{n} = {100 * ok_c / n:.0f}%   "
          f"УРОВЕНЬ: {ok_l}/{n} = {100 * ok_l / n:.0f}%")
    WORK.mkdir(parents=True, exist_ok=True)
    (WORK / "pilot_gold.json").write_text(
        json.dumps({"class_ok": ok_c, "level_ok": ok_l, "n": n,
                    "got": got}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"→ {WORK / 'pilot_gold.json'}")


def load_all() -> list[dict]:
    rows = []
    for pack, rel, tf, cf in PACKS:
        p = OUT / rel
        if not p.exists():
            print(f"  ⚠️ нет {rel}")
            continue
        for n, line in enumerate(p.open(encoding="utf-8")):
            if not line.strip():
                continue
            r = json.loads(line)
            if pack == "rgia380" and r.get("v_kataloge"):
                continue  # уже в каталоге, повторно не трогаем
            rows.append({
                "pack": pack, "n": n,
                "title": str(r.get(tf) or "").strip(),
                "ctx": str(r.get(cf) or "").strip(),
            })
    return rows


