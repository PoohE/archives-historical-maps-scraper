def collect_types() -> None:
    load_env()
    client = anthropic_client()
    rows = [json.loads(ln) for ln in RESULT.open(encoding="utf-8") if ln.strip()]
    got: dict[int, dict] = {}
    pending = 0
    for b in json.loads(BATCH2.read_text(encoding="utf-8")):
        info = client.messages.batches.retrieve(b["id"])
        if info.processing_status != "ended":
            pending += 1
            print(f"  {b['id']}: {info.processing_status}")
            continue
        for res in client.messages.batches.results(b["id"]):
            if res.result.type != "succeeded":
                print(f"  ⚠️ {res.custom_id}: {res.result.type}")
                continue
            try:
                for item in json.loads(strip_fence(answer_text(res.result.message))):
                    got[int(item["i"])] = item
            except (json.JSONDecodeError, KeyError, ValueError) as e:
                print(f"  ⚠️ {res.custom_id}: разбор — {e}")
    if pending:
        print(f"\nещё обрабатывается: {pending} пакетов — повторить позже")
        return

    with RESULT2.open("w", encoding="utf-8") as f:
        for i, r in enumerate(rows):
            g = got.get(i) or {}
            f.write(json.dumps({**r, "code": g.get("code"), "code_sure": g.get("sure"),
                                "code_why": g.get("why")}, ensure_ascii=False) + "\n")
    print(f"\nразмечено {len(got)} из {len(rows)} → {RESULT2}")
    c = Counter(str((got.get(i) or {}).get("code")) for i in range(len(rows)))
    for k, v in c.most_common():
        print(f"  {v:6d}  {k}")
    unsure = sum(1 for i in range(len(rows)) if (got.get(i) or {}).get("sure") is False)
    print(f"\nкод предположителен (sure=false): {unsure}")


def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["pilot", "submit", "collect",
                                    "submit-types", "collect-types"])
    ap.add_argument("--limit", type=int)
    args = ap.parse_args()
    if args.cmd == "pilot":
        pilot()
    elif args.cmd == "submit":
        submit(args.limit)
    elif args.cmd == "collect":
        collect()
    elif args.cmd == "submit-types":
        submit_types()
    else:
        collect_types()


if __name__ == "__main__":
    main()
