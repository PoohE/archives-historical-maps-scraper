def client_():
    load_env(ENV_PATH)
    from notion_client import Client
    return Client(auth=env("NOTION_TOKEN", required=True))


def main():
    fix_stdout()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("mode", choices=["plan", "apply", "verify"])
    args = ap.parse_args()
    logger = log("series_fill_objects")

    if args.mode == "plan":
        for pid, rec in SERIES.items():
            print(f"- {rec['_name']} ({pid}): объекты {len(rec['_obj'])}, "
                  f"полей {len([k for k in rec if not k.startswith('_')])}")
            for k in rec:
                if not k.startswith("_"):
                    print(f"    {k}: {len(rec[k])} знаков")
        return

    client = client_()
    if args.mode == "apply":
        for pid, rec in SERIES.items():
            props = {k: {"rich_text": rt(v)} for k, v in rec.items() if not k.startswith("_")}
            props["Типы отображаемых объектов"] = {"relation": [{"id": i} for i in rec["_obj"]]}
            retry(client.pages.update, page_id=pid, properties=props)
            logger.info("заполнено: %s", rec["_name"])
            time.sleep(SLEEP)
        return

    bad = 0
    for pid, rec in SERIES.items():
        p = retry(client.pages.retrieve, page_id=pid)["properties"]
        miss = [k for k in rec if not k.startswith("_")
                and not "".join(x.get("plain_text", "") for x in p.get(k, {}).get("rich_text", [])).strip()]
        nrel = len(p.get("Типы отображаемых объектов", {}).get("relation", []))
        ok = not miss and nrel == len(rec["_obj"])
        bad += not ok
        print("OK " if ok else "НЕТ", rec["_name"], "| объектов", nrel, "| пустые", miss)
        time.sleep(SLEEP)
    print(f"verify: расхождений {bad}")


if __name__ == "__main__":
    main()
