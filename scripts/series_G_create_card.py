def main() -> None:
    fix_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("position", nargs="?", help="позиция раздела Г, напр. Г1")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    if args.list or not args.position:
        print("описаны позиции:", ", ".join(DATA))
        return
    if args.position not in DATA:
        sys.exit(f"позиция {args.position} ещё не разобрана — сначала разбор, потом карточка")

    f = DATA[args.position]
    name = f["Название серии"]
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    # ⚠️ query_all по справочнику серий идёт минутами и не укладывается в таймаут —
    # проверяем наличие точечным запросом с фильтром по названию (14.11.2026).
    probe = retry(lambda: c.data_sources.query(
        data_source_id=SERIES_DS,
        filter={"property": "Название серии", "title": {"contains": name[:28]}},
        page_size=5,
    ))
    existing = probe.get("results") or []
    if existing:
        print(f"карточка уже есть: {title_of(existing[0])}")
        return
    if not args.apply:
        print(f"карточки нет — будет создана: «{name}»")
        for k, v in f.items():
            if k != "Название серии":
                print(f"  {k}: {str(v)[:110]}…")
        return

    props = {
        "Название серии": {"title": [{"text": {"content": name}}]},
        "Хронология нижняя": {"number": f["Хронология нижняя"]},
        "Хронология верхняя": {"number": f["Хронология верхняя"]},
    }
    for k, v in f.items():
        if isinstance(v, str) and k != "Название серии":
            props[k] = {"rich_text": rt(v)}
    retry(lambda: c.pages.create(parent={"database_id": SERIES_DB}, properties=props))
    print(f"карточка создана: {name}")


if __name__ == "__main__":
    main()
