WANT = ("РГВА", "ЦАМО", "РГАЭ", "РГВИА")


def main() -> None:
    fix_stdout()
    load_env(ENV_PATH)
    c = Client(auth=env("NOTION_TOKEN"))

    card = next(x for x in query_all(c, SERIES_DS) if "РККА" in title_of(x))

    links = []
    for a in query_all(c, ARCHIVES_DS):
        t = title_of(a)
        for w in WANT:
            if w in t.replace("  ", " "):
                links.append((t, a["id"]))
                break
    for t, _ in links:
        print("  архив:", t)

    props = {
        "Приоритетный анализ": {"rich_text": rt(PRIORITET)},
        "Использование в анализе (литература)": {"rich_text": rt(LITERATURA)},
    }
    if links:
        props["Архивы"] = {"relation": [{"id": i} for _, i in links]}

    retry(lambda: c.pages.update(page_id=card["id"], properties=props))
    print(f"карточка обновлена: {title_of(card)}; связано архивов: {len(links)}")


if __name__ == "__main__":
    main()
