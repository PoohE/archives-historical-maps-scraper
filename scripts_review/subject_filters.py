"""Отсев по ГЛАВНОМУ ПРЕДМЕТУ заголовка — общий для всех источников.

Выделено из `scripts_rgia/triage_fund380_review_queue.py` (правило второго раза:
те же два правила понадобились на наборе Президентской библиотеки).

Два правила, оба работают по предмету записи, а не по наличию слова где угодно:

1. `is_engineering_subject` — объект записи сооружение, а не территория
   (§1.2 object_conflict). Решение пользователя 09.10.2026: «мосты и скважины
   конечно выбрасывать» — независимо от того, назван ли рядом топоним.
   «План дачи с мельницей» — план дачи (берём), «Чертёж моста в даче» — чертёж
   моста (выбрасываем), «План и разрез воспитательного дома» — здание (выбрасываем).

2. `is_document_plan` — слово «план» в смысле документа, не карты
   (§1.1): «план развития промыслов», «план хозяйственного строительства».

У Президентской библиотеки заголовок часто начинается с префикса территории
(«Смоленская губерния. План гор. Гжатска»), поэтому перед проверкой предмета
префикс снимается — `strip_territory_prefix`.
"""
from __future__ import annotations

import re

# Префикс территории в заголовках ПрБ: «Смоленская губерния. …», «Пермская губерния.…»
TERRITORY_PREFIX = re.compile(
    r"^\s*(?:[А-ЯЁ][а-яё]+(?:ая|ой)\s+(?:губерни\w*|област\w*|наместничеств\w*)\s*\.\s*)+",
    re.I)

# Инженерно-архитектурный чертёж: предмет — сооружение/здание, не территория
SUBJECT_ENGINEERING = re.compile(
    r"^\s*(?:чертеж\w*|чертёж\w*|проект\w*|эскиз\w*|генеральн\w*\s+план\s+здани\w*)\b"
    r"|^\s*(?:[а-яё]+\w*\s+){0,2}план\w*(?:\s*,\s*(?:фасад\w*|разрез\w*|профил\w*))*\s+"
    r"(?:и\s+)?(?:общ\w*\s+)?(?:продольн\w*\s+)?"
    r"(?:профил\w*|разрез\w*|фасад\w*|мост\w*|плотин\w*|шлюз\w*|здани\w*|дом[ау]?\b|"
    r"дома\b|корпус\w*|сооружен\w*|водопровод\w*|трубопровод\w*|скважин\w*|колодц\w*|"
    r"богадельн\w*|казарм\w*|семинари\w*|церкв\w*|часовн\w*|канал\w*\s+для)", re.I)

# Фасады и разрезы — признак архитектурного чертежа: сами по себе территории не дают.
# Проверяем только когда в заголовке нет настоящего картографического объекта
# («Смоленская крепость. План, фасад стен, разрезы башен» — чертёж стен и башен;
#  «Смоленская крепость… Генеральный план» — генплан, остаётся).
FACADE = re.compile(r"\b(?:фасад\w*|разрез\w*)", re.I)

# Делопроизводственное дело или книга о планах — не сам картографический объект.
# Решение человека нужно: внутри дела планы могут быть, но это не единица каталога.
ARCHIVAL_FILE = re.compile(
    r"^\s*(?:дел[ао]\b|об\s+утверждении\b|о\s+дач[еи]\b|о\s+выполнении\b|"
    r"сборник\b|журнал\b|протокол\w*\b|переписк\w*\b|телеграмм\w*\b)", re.I)

# «План» в смысле документа, а не карты: план работ, развития, устройства, преподавания…
DOC_PLAN = re.compile(
    r"план\w*\s+(?:работ|развити|мероприяти|устройств|преподаван|хозяйствен|"
    r"производств|посевн|финансов|учебн|пятилетн|тематическ|заняти|счетов|"
    r"кампани|распространени|улучшени|строительств|снабжени|заготов)", re.I)

# …если рядом настоящий картографический объект — запись остаётся
REAL_MAP = re.compile(
    r"\b(?:карт(?:а|ы|е|у|ой)|картограмм\w*|атлас\w*|топографическ\w*|межев\w*|"
    r"геодезическ\w*|глазомерн\w*|генеральн\w*\s+план|"
    r"план\w*\s+(?:дач|город|г\.|гор\.|селени|деревн|"
    r"уезд|губерни|волост|участк|земел|лесничеств|имени|местност|крепост|"
    r"погоревш|проектн|мест[а-я]*\b))", re.I)


def strip_territory_prefix(title: str) -> str:
    return TERRITORY_PREFIX.sub("", title or "").strip()


def is_engineering_subject(title: str, *, strip_prefix: bool = False) -> bool:
    t = strip_territory_prefix(title) if strip_prefix else (title or "")
    if SUBJECT_ENGINEERING.search(t):
        return True
    return bool(FACADE.search(t)) and not REAL_MAP.search(t)


def is_archival_file_subject(title: str, *, strip_prefix: bool = False) -> bool:
    """Заголовок — дело/книга/переписка о планах, а не сам картографический объект."""
    t = strip_territory_prefix(title) if strip_prefix else (title or "")
    return bool(ARCHIVAL_FILE.search(t))


def is_document_plan(title: str) -> bool:
    """«План» как документ и при этом ни одного настоящего картографического объекта."""
    t = title or ""
    return bool(DOC_PLAN.search(t)) and not REAL_MAP.search(t)
