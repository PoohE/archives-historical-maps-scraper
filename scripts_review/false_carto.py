# Фамилии, совпадающие с нашими топонимами. «О предполагаемом переводе корабельного
# мастера И. ТАРУСОВА в Казанское адмиралтейство» — дело о человеке, Таруса здесь ни
# при чём (РГАВМФ, 24.10). Тот же класс ловушек, что «Ростовск→Ростов-на-Дону»
# и «Романовский»: название губернии сидит внутри фамилии.
# ⚠️ НАЗВАНИЕ СУДНА ПО ГОРОДУ — не территория (РГАВМФ, 24.10). «74-пушечный
# корабль ''Смоленск''. План расположения в интрюме чугунного балласта», «Транспорт
# ''Молога''. Чертёж рангоута и парусов» — это чертежи КОРАБЛЯ, а Смоленск и Молога
# тут имена судов. Семь таких дел прошли в принятые как картография.
# Срабатывает только когда рядом стоит слово-класс судна: иначе «План города
# Смоленска» тоже попал бы под раздачу.
# ⚠️ ПЕРЕМЫШЛЬ ГАЛИЦИЙСКИЙ ≠ ПЕРЕМЫШЛЬ КАЛУЖСКИЙ (РГАВМФ, 24.10). «Чертежи плана
# и профилей форта № I КРЕПОСТИ ПЕРЕМЫШЛЬ» — австро-венгерская крепость в Галиции,
# осада 1914–15 гг.; к калужскому уездному городу отношения не имеет. Признак —
# слова «крепость», «форт», «осада» рядом.
CHUZHOJ_PEREMYSHL = re.compile(
    r"(?:крепост|форт|осад|цитадел|оборонительн)\w*\s+[^.;]{0,40}?Перемышл"
    r"|Перемышл\w*\s+[^.;]{0,30}?(?:крепост|форт|осад|цитадел|оборонительн)"
    # ⚠️ Расширено 24.10 по приёмке claude-45: мимо прежнего паттерна прошли
    # СБОРНЫЕ КАРТЫ и АТЛАС оборонительных сооружений того же кластера (ф. 3Л
    # оп. 25 д. 1913, оп. 30 д. 320 и 358). Признак — галицийское окружение:
    # издание венское на немецком, вокруг Краковец, Радымно и ЯРОСЛАВ (польск.
    # Jarosław — он же дал ложную «Ярославскую губернию»).
    r"|Перемышл\w*[^.;]{0,80}?(?:Галиц|Австр|Вен[аеы]\b|Przemy|Jaros|Краковец"
    r"|Радымно|Сандомир|Львов|на\s+немецком)"
    # ⚠️ Масштаб 1:75 000 — австро-венгерская «Spezialkarte», русских губернских
    # карт в нём нет. «Сборная военно-топографическая карта Перемышля и его
    # окрестностей. Масштаб 1 : 75000» пережила первую правку: галицийских имён
    # в заголовке не было, опознаётся только по масштабу.
    r"|Перемышл\w*.{0,60}?1\s*:\s*75\s*000|1\s*:\s*75\s*000.{0,60}?Перемышл"
    r"|(?:Галиц|Австр|Przemy|Краковец|Радымно)[^.;]{0,80}?Перемышл", re.I)

# ⚠️ НАЗВАНИЕ ЖЕЛЕЗНОЙ ДОРОГИ ПО ГОРОДУ — не место работ (приёмка claude-45, 24.10).
# «Московско-Виндаво-РЫБИНСКАЯ железная дорога» давала Ярославскую губернию трём делам,
