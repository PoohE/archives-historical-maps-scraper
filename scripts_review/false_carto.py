    r"|(?:анатоми\w*|гистолог\w*|патолог\w*|хирурги\w*)\s*[:,]\s*атлас"
    # Советские плановые и отчётные документы (к пятилетним планам)
    r"|семилетн\w+\s+план|комплексн\w+\s+план|единн?\w+\s+план"
    r"|план\w*\s+(?:племенн|экскурсионн|лекционн|воспитательн|учебн|издательск)"
    r"|план\w*\s+(?:социально-)?экономическ\w+\s+развити"
    r"|план\w*\s+основных\s+мероприяти|план\w*\s+научно-техническ"
    # Делопроизводство органов власти: решения сессий советов, постановления
    # парткомов. Слово «план» стоит внутри формулировки решения («о плане
    # благоустройства»), а предмет записи — распорядительный документ.
    r"|Совет\w*\s+(?:депутатов|народных\s+депутатов)|Созыв\s*\(|Сессия\s*\("
    r"|Решение\s*\.{0,3}\s*(?:№\s*\d+\s*)?от\s+\d|Постановление\s*\.{0,3}\s*(?:№|от)"
    r"|\bКПСС\b|Пленум|Исполнительный\s+комитет"
    r"|^Инструкция\b|^Рекомендации\b|в\s+помощь\s+работнику"
    r"|(?:лекарственн\w+\s+)?растени\w*\s*:\s*атлас"
    # «в организационном плане», «в плане развития» — план как аспект
    r"|в\s+организационн\w+\s+план|в\s+план[ае]\s+(?:развити|рассмотрени)"
    r"|восточн\w+\s+серебр"
    # «НА ПЕРВОМ ПЛАНЕ» — это фотография вида, а не план местности: «Общий вид
