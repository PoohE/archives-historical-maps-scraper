    r"|(?:Смоленск|Калужск|Ярославск|Пермск)\w*\s+(?:биржев\w+\s+)?артел"
    # ГОДОНИМ ≠ ТЕРРИТОРИЯ (добавлено 22.10). Улица, проспект, переулок, площадь,
    # шоссе, набережная или слобода, названные по губернии, встречаются в ЛЮБОМ
