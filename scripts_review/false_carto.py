    r"|план\w*\s+выработки|план\w*\s+(?:общих\s+)?оснований\s+оценки"
    # Советское планирование: «погубернские посевные планы», «план заготовок»,
    # «производственный план» — слово «план» в смысле задания, не чертежа
    # (ЭБИД 21.10: единственная «принятая» запись оказалась постановлением СНК
    # о посевных планах)
    r"|посевн\w+\s+план|план\w*\s+посев|план\w*\s+заготов|производственн\w+\s+план"
    # ⚠️ «ПЯТИЛЕТНИЙ ПЛАН хозяйства Кунгурского округа», «Пятилетний план развития
    # хозяйства и работы Пермской железной дороги» — плановое задание советской
    # экономики, а не чертёж (Белинка, 22.10: три записи прошли как картография)
    r"|пятилетн\w+\s+план|перспективн\w+\s+план|контрольн\w+\s+цифр"
