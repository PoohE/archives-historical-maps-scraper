    r"|(?:улиц\w*|переул\w*|проспект\w*|площад\w*|шоссе|набережн\w*)\s+"
    r"(?:Калужск|Смоленск|Ярославск|Пермск)\w*"
    # ВЛАДЕЛЕЦ-ПРЕДПРИЯТИЕ ≠ МЕСТО: «План дачи ЧЕРЕПОВЕЦКОГО уезда… владения
    # ЯРОСЛАВСКОЙ Большой мануфактуры» — земля в Новгородской губернии
    r"|владени\w*\s+(?:[^,;]{0,40}?)(?:Калужск|Смоленск|Ярославск|Пермск)\w*\s+"
