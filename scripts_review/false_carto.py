def is_false_carto(title: str) -> str | None:
    """Вернуть сработавший паттерн, если «карта/план/чертёж» здесь не о карте.

    «Ситуационный план» проверяется первым: он привязывает объект к местности и
    остаётся в скоупе, даже когда рядом стоят фасады и этажи.
    """
    t = title or ""
    m = FALSE_CARTO.search(t)
    return m.group(0) if m else None


def alien_hit(title: str) -> str | None:
    """Вернуть название чужой территории, если она названа в заголовке."""
    m = ALIEN_TERRITORY.search(title or "")
    return m.group(0) if m else None


def not_a_place(title: str) -> str | None:
    """Вернуть вхождение, где название губернии — не топоним (престол, сословие, фамилия)."""
    m = NOT_A_PLACE.search(title or "")
    if m:
        return m.group(0)
    m = FAMILIYA_NE_MESTO.search(title or "")
    if m:
        return f"фамилия, а не место: {m.group(0)}"
    m = SUDNO_NE_MESTO.search(title or "")
    if m:
        return f"название судна, а не место: {m.group(0)[:40]}"
    m = CHUZHOJ_PEREMYSHL.search(title or "")
    if m:
        return f"Перемышль в Галиции, не Калужская губ.: {m.group(0)[:36]}"
    m = ZHD_NE_MESTO.search(title or "")
    if m:
        return f"название железной дороги, а не место: {m.group(0)[:40]}"
    m = VOINSKAYA_CHAST.search(title or "")
    if m:
        return f"название воинской части, а не место: {m.group(0)[:36]}"
    m = PERMSKOE_NA_AMURE.search(title or "")
    return f"село Пермское на Амуре, не Пермская губ.: {m.group(0)[:36]}" if m else None
