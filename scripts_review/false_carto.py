    r"|^письм\w*\s|^телеграмм|^удостоверени|^мандат|^справк[аи]\s"
    r"|план\w*\s+снабжени|план\w*\s+перевозок|финансов\w+\s+план|план\w*\s+наборa?"
    # Архитектурная документация отдельного здания — не территориальный источник
