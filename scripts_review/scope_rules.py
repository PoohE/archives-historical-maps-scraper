"""Правила отбора по профилю и территории — общие для всех библиотечных источников.

Заведено 21.10.2026, когда одни и те же перечни уездов и классов понадобились третьему
сборщику подряд (ГПИБ → ЭБИД → Президентская библиотека). Правило второго раза: держать
в одном месте, а не копировать регулярки между скриптами, иначе исправление в одном
сборщике не доходит до остальных — именно так «Уфимск» без границы слова жил в гейте
Госкаталога и съедал красноуфимские (то есть ПЕРМСКИЕ) записи.

Ловушки ложных срабатываний живут отдельно, в `false_carto.py`: там «чего НЕ брать»,
здесь — «что брать и к какой территории относить».
"""
from __future__ import annotations

import re

# --- Классы, принимаемые в каталог от библиотек ----------------------------------
# 1. Картография в прямом смысле
CARTO = re.compile(
    r"\bкарт[аыуеой]\b|\bкарты\b|\bкарт\b|\bатлас\w*|\bплан[ыаеуов]?\b|\bпланы\b"
    r"|чертеж|чертёж|съемк|съёмк|топографическ\w+\s+(?:карт|съемк|съёмк)|межев"
    r"|картосхем|картограмм|глобус|поволостн\w+\s+план", re.I)

# 2. Пространственное описание территории — в проекте идёт наравне с картами
#    (так уже внесены «Списки населённых мест», «Топографическое описание Ярославского
#    наместничества», «Материалы для географии и статистики» Генштаба)
SPATIAL_DESC = re.compile(
    r"статистическ\w+\s+описани|оценочно-статистическ|список\w*\s+населенн\w+\s+мест"
    r"|списки\s+населенн\w+\s+мест|населенн\w+\s+мест\w*\s+по\s+сведениям"
    r"|памятн\w+\s+книжк|адрес-календар|справочн\w+\s+книжк"
    r"|материал\w*\s+для\s+географии|военно-статистическ\w+\s+обозрени"
    r"|топографическ\w+\s+описани|географическо-статистическ|статистическ\w+\s+обзор"
    # ⚠️ Добавлено 22.10 (Белинка): «КРАТКОЕ ГЕОГРАФИЧЕСКОЕ ОПИСАНИЕ и обзор
    # хозяйства Ирбитского округа» отсеивалось как «не наш класс» — в перечне
    # были топографическое и статистическое описания, а географического не было
    r"|географическ\w+\s+(?:описани|очерк|обзор)|экономико-статистическ"
    r"|статистико-экономическ\w+\s+описани"
    # Почтовый дорожник — описание сети дорог, станций и расстояний
    r"|почтов\w+\s+словар|дорожник|описыва\w+\s+(?:все\s+)?почтов\w+\s+тракт"
    r"|статистическ\w+\s+сборник|обзор\w*\s+\w*\s*губернии"
    r"|труд\w*\s+\w*\s*губернского\s+статистическ|губернск\w+\s+статистическ\w+\s+комитет"
    r"|сборник\w*\s+статистическ\w+\s+сведений|подворн\w+\s+опис|перепис"
    # «Волости и гмины 1890 года» — издание ЦСК по волостному делению; без этой
    # строки тома «40. Смоленская губерния», «50. Ярославская», «31. Пермская»
    # уходили в отсев как «ни картографии, ни описания» (поймано 22.10)
    r"|волост\w+\s+и\s+важнейш\w+\s+селени|волост\w+\s+и\s+гмин|словар\w+\s+географическ",
    re.I)

# 3. Межевые и писцовые книги — ОТДЕЛЬНЫЙ класс по решению пользователя: это описания
#    границ и угодий (46,6 тыс. текстовых книг), с картами их не смешивать
MEZHEVYE = re.compile(
    r"межев\w+\s+книг|писцов\w+\s+книг|дозорн\w+\s+книг|переписн\w+\s+книг"
    r"|межев\w+\s+опис|книг\w*\s+межевани", re.I)

# --- ПРАВИЛО МАСШТАБА ОБЪЕКТА (решение пользователя 21.10.2026) ------------------
# «Берём территорию, не постройку». Планы, чертежи и схемы ОТДЕЛЬНЫХ объектов —
# промышленных, хозяйственных, жилых, культовых — в каталог не идут. Берём
# территориальные единицы начиная с земельной дачи: дачи и лесные дачи, пустоши,
# поля, угодья, выселки, деревни, сёла, волости, станы, уезды, губернии.
# ⚠️ Это правило ОТМЕНИЛО прежнее исключение «ситуационный план здания — в скоупе».
# ⚠️ Ловим ОБЪЕКТ плана, а не любое упоминание постройки. Первая версия отсеивала
# «BUILDING и не TERRITORY», но в заголовке почти всегда есть «…уезд, деревня N»,
# и территория отменяла отсев: 39 планов мельниц остались принятыми. Поэтому смотрим,
# ЧТО именно планируется — слово сразу после «план/чертёж/схема».
# ⚠️ Заводские сооружения добавлены 22.10 (добор Госкаталога по Екатеринбургу):
# «План и профиль гармахерского ГОРНА», «План СКОТОБОЙНИ, купленной Думой…» —
# это агрегат и постройка, а не территория.
_BLD = (r"мельниц|дом[аеу]\b|дома\b|кузниц|лавк|амбар|сара|бан[ия]|церкв|часовн"
        r"|собор|колокольн|здани|корпус|цеха|фабрик|мастерск|склад|конюшн"
        r"|этаж|подвал|комнат|квартир|флигел|ограды|крыльц"
        r"|скотобойн|бойн|горн[ау]?\b|домн|вагранк|печ[иь]\b"
        r"|мост[ауые]?\b|дамб|шлюз|пристан"
        r"|крепостн\w+\s+стен|башн|вал[аы]?\b|бастион")
# ⚠️ ДЕФИС В ПОРЯДКОВОМ ЧИСЛИТЕЛЬНОМ. Промежуточные слова берём как `[\w-]+`, а не
# `\w+`: «План ВТОРОГО этажа» ловился, а «План 2-ГО этажа» — нет, потому что `\w`
# не проходит через дефис. Из-за этого 10 планов этажей (усадьба Гончаровых в Калуге,
# шесть обмеров башен смоленской крепостной стены, дом гр. Александрова, два листа
# по Очеру и Пожве) прошли гейт Госкаталога как принятые (найдено 22.10).
BUILDING = re.compile(
    # ⚠️ «ситуационный план» — тоже постройка (решение пользователя 21.10: последний
    # пограничный случай «Гостиный двор. Ситуационный план» разрешён как «не берём»)
    r"ситуационн\w+\s+план"
    rf"|(?:план|чертеж|чертёж|схема)\w*\s+(?:[\w-]+\s+){{0,3}}(?:{_BLD})"
    r"|поэтажн\w+\s+план|план\w*\s+(?:[\w-]+\s+){0,3}этаж"
    r"|\d+[-\s]*х?\s*этажн"
    r"|фасад|продольн\w+\s+разрез|поперечн\w+\s+разрез|интерьер"
    r"|дом[аы]?\s+\w+[,\s]+(?:жител|кресть|купц|мещан)"
    r"|план\w*\s+усадебн\w+\s+места\s+дома", re.I)
# Объект плана — территориальная единица: такие НЕ отсеиваем, даже если рядом завод
# («План хозяйства на Бисерскую ЗАВОДСКУЮ ДАЧУ», «план лесной дачи»)
BUILDING_EXCEPT = re.compile(
    r"(?:план|чертеж|чертёж|схема|хозяйств\w*)\w*\s+(?:на\s+)?(?:[\w-]+\s+){0,3}"
    r"(?:дач[иауеуы]|дачу|пустош|угодь|надел|выгон|покос|пашн|лесничеств|округ)", re.I)
# Территориальная единица — то, что всё-таки берём, даже если рядом стоит объект
TERRITORY = re.compile(
    r"\bдач[иауе]\b|\bдачу\b|лесн\w+\s+дач|заводск\w+\s+дач|приисков\w+\s+дач"
    r"|пустош|урочищ|выселк|пашн|покос|выгон|луг[аов]|угодь|надел"
    r"|деревн|сел[ао]\b|слобод|посад|волост|\bстан[ау]?\b|уезд|губерни"
    r"|наместничеств|округ[аи]?\b|дистрикт", re.I)
# Сопроводительные издания к картам и к межевым работам — БЕРЁМ (уточнение 21.10):
# «указатель к межевой карте N-ского уезда», «к новой карте N-ского уезда»,
# «план землеустроительных работ» (документ о ПРОВЕДЁННОМ межевании).
MAP_COMPANION = re.compile(
    r"указател\w+\s+к\s+(?:межев\w+\s+)?карт|к\s+нов\w+\s+карт|приложени\w*\s+карт"
    r"|с\s+(?:прил\w*\.?\s*)?карт|с\s+планом\s+город|медико-топографическ"
    r"|землеустроительн\w+\s+работ|межев\w+\s+работ|съемочн\w+\s+работ", re.I)

# --- Карты ВНУТРИ издания: иллюстративный состав, а не класс ---------------------
# «198 с.: ил., карты», «270 с.: карты, табл.» — это сведения об иллюстрациях в книге.
# Признак ценный (книга с картой внутри), но классом издания НЕ является: иначе
# военно-научный журнал с картами боевых действий становится картографией.
ILLUSTR_KARTY = re.compile(
    r"\d+\s*с\.\s*:[^.;]{0,60}?(?:карт|план|черт|атлас)"
    r"|:\s*(?:ил\.?,?\s*)?(?:карт[аы]|планы|чертежи)\b", re.I)


# --- Карта в приложении к тому — самая ценная пометка ----------------------------
# ⚠️ Разделители необязательные: «1. л. карт» встречается с точкой и после цифры,
# и после «л». Без этого лист карт при издании теряется.
PRILOZHENIE = re.compile(
    r"с\s+приложением[^.;]{0,80}(?:карт|план|атлас)|прил(?:\.|ожени\w+)[^.;]{0,60}"
    r"(?:карт|план)|\d+\s*[.,]?\s*л\w*\.?\s*(?:карт|план|черт|атлас)", re.I)

# --- Территория: губернии проекта и их уезды -------------------------------------
# Перечни полные, включая уезды, которых не хватало в прежних сборщиках:
# Малоярославецкий (Калужская), Бельский и Краснинский (Смоленская),
# Красноуфимский, Камышловский, Екатеринбургский (все — ПЕРМСКОЙ губернии).
#
# ⚠️ ДОКУМЕНТЫ XVIII в. НАЗЫВАЮТ ДРУГИЕ ГОРОДА. На 1761 год Калужской и Ярославской
# губерний ещё нет (учреждены 1776 и 1777), дела идут по воеводским канцеляриям, и в
# перечне обязаны быть города, упразднённые позже: Серпейск, Воротынск, Оболенск,
# Передольск (все — калужские), а Екатеринбург встречается как «г. Екатеринбург и его
# уезд», без формы «Екатеринбургский уезд» (пропуск найден на описях СПбФ АРАН 21.10).
GUB = {
    "Калужская": r"Калуж|Боровск|Козельск|Медын|Мосальск|Тарус|Жиздр|Мещовск|Мещевск"
                 r"|Перемышл|Лихвин|Малоярославец|Малоярославск"
                 r"|Серпейск|Воротынск|Оболенск|Передольск",
    # ⚠️ «Рославл» ТОЛЬКО с границей слова: без неё смоленский Рославль ловится
    # внутри «ЯРОСЛАВЛь» и приписывает Смоленскую губернию ярославским изданиям
    # (71 запись пакета ПБ 21.10 получила «Смоленская; Ярославская»).
    "Смоленская": r"Смоленск|Вязьм|Вязем|Гжатск|Дорогобуж|Духовщин|\bРославл|Юхнов"
                  r"|Ельнин|Поречск|Сычев|Бельск\w*\s+уезд|Краснинск",
    # ⚠️ «Ярослав» ТОЛЬКО не внутри «МалоЯРОСЛАВецкий» — калужский город
    # Малоярославец давал ложную вторую губернию (node 78312/78313 ГПИБ)
    "Ярославская": r"(?<!Мало)Ярослав|Углич|Мышкин|Пошехон|Молог|Рыбинск|Любим|Данилов"
                   r"|Романово-Борис|Романов-Борис",
    # ⚠️ Советские имена наших городов (добавлены 22.10 по находке в Белинке):
    # Молотов = Пермь (1940–1957), Свердловск = Екатеринбург (1924–1991).
    # «Молотовск» без слова «область» НЕ берём: так назывались и Северодвинск
    # в Архангельской области, и город в Кировской.
    "Пермская": r"Пермск|\bПерм[ьи]\b|Соликамск|Чердын|Кунгур|Оханск|Осинск|Верхотур"
                r"|Ирбит|Шадринск|Прикам|Красноуфимск|Красно-Уфимск|Камышлов"
                r"|Екатеринбург|Свердловск"
                r"|Молотовск\w+\s+(?:обл|област)|город\w*\s+Молотов\b|\bг\.\s*Молотов\b",
}
# «Ростов» вынесен отдельно: ярославский Ростов неотличим от Ростова-на-Дону без
# уездного контекста (ловушка срабатывала ТРИЖДЫ в трёх разных сборщиках)
ROSTOV_OUR = re.compile(r"Ростовск\w+\s+уезд|Ростов\s+Ярославск|Ростов\s+Велик"
                        r"|Ростов\w*\s+Ярославск|Ростовск\w+\s+воеводск", re.I)
# «Романов» — такая же ловушка: ярославский Романов (позже Романово-Борисоглебск) и
# Романов в Степи (Липецкий край, рядом с Белоколодском). Требуется контекст.
# Найдено на описях СПбФ АРАН 21.10: д. 90 «Романовская и Белоколодская воеводская
# канцелярия» — чужой Романов, д. 8 «Романовская воеводская канцелярия (Ярославская
# провинция)» — наш.
ROMANOV_OUR = re.compile(r"Романов\w*\s*\(?Ярославск|Романово?-Борисоглеб"
                         r"|Романов\w+\s+уезд\w*\s+Ярославск", re.I)
ROMANOV_ALIEN = re.compile(r"Романов\w*\s+и\s+Белоколодск|Белоколодск", re.I)

YEAR = re.compile(r"\b(1[5-9]\d{2}|19[0-8]\d)\b")
LIMIT = 1989  # правило пользователя: для библиотек верхняя граница 1989 год включительно


def territories(blob: str) -> list[str]:
    """Губернии проекта, названные в тексте карточки.

    «Ростов» и «Романов» добавляются только при уездном или губернском контексте:
    без него это может быть Ростов-на-Дону и Романов в Степи.
    """
    found = [g for g, p in GUB.items() if re.search(p, blob, re.I)]
    if "Ярославская" not in found and ROSTOV_OUR.search(blob):
        found.append("Ярославская")
    if ("Ярославская" not in found and ROMANOV_OUR.search(blob)
            and not ROMANOV_ALIEN.search(blob)):
        found.append("Ярославская")
    return sorted(set(found))


def klass(blob: str, carto_ok: bool = True) -> str:
    """Класс источника: межевые книги → картография → пространственное описание."""
    if MEZHEVYE.search(blob):
        return "межевые книги"
    if carto_ok and CARTO.search(blob):
        return "картография"
    if SPATIAL_DESC.search(blob):
        return "пространственное описание"
    return ""


#   «Памятная книжка Смоленской губернии… НА 1900 ГОД», «Обзор Калужской губернии
#   ЗА отчётный 1891 год» — у серийных изданий год ТОМА стоит в заголовке, а поле
#   «Год издания» несёт годы всей серии («1855-1916»). Для каталога нужен год тома.
TOM_YEAR = re.compile(r"(?:на|за)\s+(?:отчетн\w+\s+|отчётн\w+\s+)?(1[5-9]\d{2}|19[0-8]\d)"
                      r"(?:[-–/]\d{2,4})?\s*(?:год|г\b|гг)", re.I)


def god_iz(blob: str, declared: str = "", title: str = "") -> tuple[str, int | None]:
    """Год как строка и как число для сравнения с границей 1989.

    Приоритет: год ТОМА из заголовка («на 1900 год») → объявленное поле «Год
    издания» → любой год из текста. Иначе серийное издание получает год начала
    серии, и в каталоге у тома 1900 года окажется 1855-й.
    """
    god = ""
    m_tom = TOM_YEAR.search(title or "") or TOM_YEAR.search(blob)
    if m_tom:
        god = m_tom.group(1)
    if not god:
        god = declared or ""
    if not god:
        yy = YEAR.findall(blob)
        god = max(yy) if yy else ""
    m = re.search(r"(1[5-9]\d{2}|20[0-2]\d)", str(god))
    return god, (int(m.group(1)) if m else None)
