"""ГАКО: сборка списка поисковых ссылок для РУЧНОГО прохода пользователем.

Почему вручную: `archive.admoblkaluga.ru/robots.txt` адресно запрещает ИИ-агентам
(`User-agent: anthropic-ai` → `Disallow: /`, строки 677–678; рядом GPTBot, ChatGPT-User,
CCBot), при этом группе `*` не запрещено ничего. Запросы к серверу делает пользователь
своим браузером, мы разбираем сохранённые страницы.

Поиск фразовый и чувствителен к падежу (урок УИАД: «карта Калужская губерния» → 0,
«карта Калужской губернии» → 6), поэтому формулировки перебираются по падежам и
синонимам, а не одним словом с усечением.

Запуск:
    python -B scripts_gako/make_gako_queries.py --out C:\\arch\\gako_in
"""
from __future__ import annotations

import argparse
import sys
import urllib.parse
from pathlib import Path

BASE = "https://archive.admoblkaluga.ru/gako/search"
# служебные параметры взяты из живой ссылки пользователя 13.10.2026
FIXED = {"type": "simple", "p0.t": "", "p0.d": "", "p0.c": "12",
         "p0.a": "19280", "pageSize": "100"}

QUERIES = [
    # территория + вид документа
    "карта Калужской губернии",
    "план Калужской губернии",
    "атлас Калужской губернии",
    "чертеж Калужской губернии",
    "карта Калужского уезда",
    "план города Калуги",
    "план Калуги",
    # межевание как предмет
    "генеральное межевание",
    "специальное межевание",
    "межевание",
    "размежевание",
    "межевая книга",
    "межевые книги",
    "планы дач",
    "план дачи",
    "экономические примечания",
    # съёмка и землеустройство
    "топографическая карта",
    "геодезические работы",
    "землемер",
    "планы земельных участков",
    "выкопировка",
    # уезды губернии — территориальный охват
    "Боровского уезда",
    "Жиздринского уезда",
    "Козельского уезда",
    "Лихвинского уезда",
    "Малоярославецкого уезда",
    "Медынского уезда",
    "Мещовского уезда",
    "Мосальского уезда",
    "Перемышльского уезда",
    "Тарусского уезда",
]


def url_for(q: str) -> str:
    params = {"p0.v": q, **FIXED}
    return f"{BASE}?{urllib.parse.urlencode(params)}"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="папка для сохранения страниц и списка")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    lines = [
        "# ГАКО: ссылки для ручного прохода",
        "",
        f"Запросов: {len(QUERIES)}. Выдача по 100 записей на страницу.",
        "",
        "**Как работать:** открыть ссылку → если результаты есть, раскрыть описи "
        "(«Дело (N)») → сохранить страницу Ctrl+S, тип **«Веб-страница, полностью»**, "
        f"в папку `{out}` → отметить галочкой в таблице ниже.",
        "",
        "⚠️ Поиск ищет ОПИСИ, а не дела: «5 результатов» = 5 описей, внутри которых "
        "могут быть сотни дел. У многих дел в базе нет заголовка — только шифр.",
        "",
        "| ✓ | запрос | найдено | ссылка |",
        "|---|---|---|---|",
    ]
    for q in QUERIES:
        lines.append(f"|  | {q} |  | {url_for(q)} |")
    lines += [
        "",
        "## Что записывать в колонку «найдено»",
        "",
        "Число из строки «Результаты поиска: 1-N из M» — достаточно M. Если ноль, "
        "так и пишите «0», это тоже результат: он показывает, что формулировка не та.",
    ]

    f = out / "ЗАПРОСЫ_ГАКО.md"
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"запросов: {len(QUERIES)}")
    print(f"список: {f}")
    print("\nпервые три ссылки для проверки:")
    for q in QUERIES[:3]:
        print(f"  {q}\n    {url_for(q)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
