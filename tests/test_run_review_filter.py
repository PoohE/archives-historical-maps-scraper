"""Регрессионный тест фильтра review-run.

Защита «чтобы ошибка не повторялась»: эталонный набор реальных примеров из прогонов ПрБ
(шум, который ДОЛЖЕН отсеиваться; настоящие карты, которые ДОЛЖНЫ оставаться/на проверку).
Прогонять после ЛЮБОЙ правки фильтра (run_review.decide / triggers). Провал = регрессия.

Запуск: pytest tests/test_run_review_filter.py   ИЛИ   python tests/test_run_review_filter.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts" / "modules"))

from run_review import decide, title_year_over  # noqa: E402
from triggers import classify  # noqa: E402

LO, HI = 1600, 1939


def bucket(title, desc="", yf=None, yt=None, url=""):
    rec = {"title": title, "description": desc, "place": "",
           "year_from": yf, "year_to": yt, "url": url}
    return decide(rec, "prlib", set(), set(), LO, HI)[0]


# ── ДОЛЖНО отсеиваться (чужой регион / жанр не-карта / вне периода) ───────────
DROP = [
    ("Дневник последняго похода Стефана Батория на Россию (осада Пскова) и дипломатическая переписка того времени", ""),
    ("Кунгурская пещера // Русский репортер. 2014, № 4 (332)", ""),
    ("Ростов на Дону", "Историко-экономический очерк"),
    ("Материалы для описания русских рек. Вып. 25. Изыскания реки Дона 1906-1909 гг.", ""),
    ("Карта Иркутской губернии", ""),
    ("Поход под Казань, ее осада и взятие в 1552 году", ""),
    ("Примерный штат Тверской губернии", ""),
    ("Цветущее состояние всероссийского государства", "губернии Санктпетербургская, Московска"),
]

# ── ДОЛЖНО авто-оставляться (карта нашего региона в периоде) ──────────────────
KEEP = [
    ("Атлас Калужскаго наместничества", "", 1785, 1785),
    ("Карта Переславль-Залесского уезда Владим. губ.", "", 1896, 1896),
    ("[Атлас Смоленской губернии]", "", None, None),
]

# ── ДОЛЖНО уходить на ручную проверку (в регионе, но без маркера карты / сомнит.) ─
REVIEW = [
    ("Смоленская губерния", "", 1913, 1913),
    ("Ярославская губерния", "", 1913, 1913),
    ("Опыт статистического обозрения Калужской губернии", "", 1838, 1838),
    ("Списки населенных мест Российской империи по Калужской губернии", "", 1863, 1863),
    ("Военно-статистическое обозрение Российской империи. Смоленская губерния", "", 1852, 1852),
    # травелоги/летописи и их описания — берём на проверку (внутри бывают карты)
    ("Путешествие в города Чердынь и Соликамск.", "", 1821, 1821),
    ("Путевые записки по России, в двадцати губерниях",
     "С.-Петербургской, Тверской, Московской, Ярославской, Костромской и Нижегородской", 1843, 1843),
    ("Краткая сибирская летопись (Кунгурская)", "", 1880, 1880),
    # «Сибирь» в названии не отсеиваем (Пермь под именем Сибирь)
    ("Схема ветров и распределения атмосферных осадков Сибири", "", None, None),
]


def test_drops():
    for t, d in DROP:
        assert bucket(t, d) == "drop", (t, bucket(t, d))


def test_keeps():
    for t, d, yf, yt in KEEP:
        assert bucket(t, d, yf, yt) == "keep", (t, bucket(t, d, yf, yt))


def test_reviews():
    for t, d, yf, yt in REVIEW:
        assert bucket(t, d, yf, yt) == "review", (t, bucket(t, d, yf, yt))


def test_perepis_not_perepiska():
    # корень бага: «переписка» ≠ «перепись»
    assert classify("дипломатическая переписка того времени") == "negative"
    assert classify("перепись населения") == "doubtful"


def test_title_year():
    assert title_year_over("Кунгурская пещера 2014", 1939) is True
    assert title_year_over("Карта Калужской губернии 1863 года", 1939) is False


def test_in_notion():
    rec = {"title": "Атлас", "url": "https://prlib.ru/item/1", "year_from": 1800, "year_to": 1800}
    assert decide(rec, "prlib", {"https://prlib.ru/item/1"}, set(), LO, HI)[0] == "in_notion"


if __name__ == "__main__":
    for fn in (test_drops, test_keeps, test_reviews, test_perepis_not_perepiska,
               test_title_year, test_in_notion):
        fn()
        print("ok:", fn.__name__)
    print("ALL PASS")
