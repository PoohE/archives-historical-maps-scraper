def _unpack(row):
    """Кортеж (title, desc[, yf, yt]) → аргументы bucket()."""
    t, d = row[0], row[1]
    yf = row[2] if len(row) > 2 else None
    yt = row[3] if len(row) > 3 else None
    return t, d, yf, yt


def test_drops():
    for row in DROP:
        t, d, yf, yt = _unpack(row)
        assert bucket(t, d, yf, yt) == "drop", (t, bucket(t, d, yf, yt))


def test_keeps():
    for row in KEEP:
        t, d, yf, yt = _unpack(row)
        assert bucket(t, d, yf, yt) == "keep", (t, bucket(t, d, yf, yt))


def test_reviews():
    for row in REVIEW:
        t, d, yf, yt = _unpack(row)
        assert bucket(t, d, yf, yt) == "review", (t, bucket(t, d, yf, yt))


def test_perepis_not_perepiska():
    # корень бага: «переписка» ≠ «перепись»
    assert classify("дипломатическая переписка того времени") == "negative"
    assert classify("перепись населения") == "doubtful"


def test_title_year():
    assert title_year_over("Кунгурская пещера 2014", 1939) is True
    assert title_year_over("Карта Калужской губернии 1863 года", 1939) is False


def test_in_notion():
    rec = {"title": "Атлас", "url": "https://prlib.ru/item/1", "year_from": 1800, "year_to": 1800}
    assert decide(rec, "prlib", {"https://prlib.ru/item/1"}, set(), LO, HI)[0] == "in_notion"


